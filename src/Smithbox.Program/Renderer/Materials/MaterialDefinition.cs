    public static MaterialDefinition FromMatbin(string name, MATBIN matbin, MaterialShaderTable? table)
    {
        MaterialDefinition def = new() { Name = name, Source = "MATBIN" };

        foreach (MATBIN.Param param in matbin.Params)
        {
            def.Params[ShortParamName(param.Name)] = ToFloats(param.Value);
        }

        foreach (MATBIN.Sampler sampler in matbin.Samplers)
        {
            def.Samplers.Add(ParseSampler(sampler.Type, sampler.Path, [sampler.Unk14.X, sampler.Unk14.Y]));
        }

        def.Finish(matbin.ShaderPath, table);
        return def;
    }

    public static MaterialDefinition FromMtd(string name, MTD mtd, MaterialShaderTable? table)
    {
        MaterialDefinition def = new() { Name = name, Source = "MTD" };

        foreach (MTD.Param param in mtd.Params)
        {
            def.Params[ShortParamName(param.Name)] = ToFloats(param.Value);
        }

        foreach (MTD.Texture texture in mtd.Textures)
        {
            def.Samplers.Add(ParseSampler(texture.Type, texture.Path ?? "", []));
        }

        def.Finish(mtd.ShaderPath, table);
        return def;
    }

    private void Finish(string shaderPath, MaterialShaderTable? table)
    {
        // Shader paths are Windows network paths, so Path can't be relied on to split them on every platform
        ShaderName = Path.GetFileNameWithoutExtension(shaderPath.Split('\\', '/')[^1]);
        ShaderTokens = ShaderToken.Matches(ShaderName).Select(m => m.Groups[1].Value).ToList();

        BlendMode = (int)GetFirst("g_BlendMode", 0);
        AlphaRef = (int)GetFirst("g_AlphaRef", 0);
        CullNone = GetFirst("g_GX_PrimCullNone", 0) != 0;
        DisableDepthWrite = GetFirst("g_GX_bDisableDepthWrite", 0) != 0;
        MeshDecal = GetFirst("g_GX_bMeshDecal", 0) != 0;

        if (Params.TryGetValue("g_DiffuseMapColor", out var color) && color.Length >= 3)
        {
            DiffuseColor = color[..3];
        }

        ResolveBlendLayers();
        ResolveTiling(table);
        ResolveTextureInputs(table);

        if (table != null && table.Shaders.TryGetValue(ShaderName, out MaterialShaderEntry? entry))
        {
            ApplyShaderEntry(entry);
        }

        ResolveBlendRecipe(table);
        ResolveDetailRecipe(table);
        ResolveMagmaRecipe(table);
        ResolveSurface();
        ResolveWater(table);
        ResolveFur(table);
        ResolveMetallic(table);
        ResolveEmissiveMask(table);

        if (table != null && table.UvSets.TryGetValue(ShaderName, out var uvSets))
        {
            foreach (MaterialSampler sampler in Samplers)
            {
                if (sampler.Slot >= 0 && uvSets.TryGetValue(sampler.Slot, out var set) && int.TryParse(set, out var value))
                {
                    sampler.UvSet = value;
                }
            }
        }
    }

    /// <summary>The sampler type of the texture whose red is the glow, see <see cref="MaterialEmissiveMask"/></summary>
    public string? EmissiveMaskType { get; set; }

    /// <summary>
    /// A glow from a texture that isn't named as one (M[Crystal]'s Mask1Map). A material that has its own emissive map
    /// in that slot is left as it is, as the name already routes it
    /// </summary>
    private void ResolveEmissiveMask(MaterialShaderTable? table)
    {
        var staticSwitch = (int)GetFirst("GXFT_SATStaticSwitch", 0);
        MaterialEmissiveMask? mask = null;
        foreach (var key in new[] { $"{ShaderName}@{staticSwitch}", $"{ShaderName}@0", ShaderName })
        {
            if (table != null && table.EmissiveMasks.TryGetValue(key, out mask))
            {
                break;
            }
        }

        MaterialSampler? sampler = mask == null ? null : Samplers.Find(x => x.Slot == mask.Slot);
        if (mask == null || sampler == null || sampler.Role.Contains("Emissive", StringComparison.OrdinalIgnoreCase))
        {
            return;
        }

        EmissiveMaskType = sampler.Type;

        var color = mask.Color != null && Params.TryGetValue(mask.Color, out var c) && c.Length >= 3 ? c[..3] : [1f, 1f, 1f];
        var factor = mask.Factor == null ? 1 : EvaluateProduct(mask.Factor);
        sampler.Color = color.Select(x => x * factor).ToArray();
    }

    private const string MetallicRole = "MetallicMap";

    /// <summary>
    /// The offset of each metallic map, from the shader's table, and which metallic map goes with each blend layer:
    /// the one in the UV group of the layer's albedo, as the shaders lerp a layer's albedo and metallic by the same
    /// weight and sample them with the same UVs. Failing that, the one with the albedo's number.
    /// </summary>
    private void ResolveMetallic(MaterialShaderTable? table)
    {
        List<MaterialSampler> metals = Samplers.Where(x => x.Role == MetallicRole).ToList();
        if (metals.Count == 0)
        {
            return;
        }

        Dictionary<int, string>? offsets = null;
        table?.Metallic.TryGetValue(ShaderName, out offsets);

        foreach (MaterialSampler metal in metals)
        {
            if (offsets == null || !offsets.TryGetValue(metal.Slot, out var entry) || entry == "")
            {
                continue;
            }

            var parts = entry.Split(':');
            var component = parts.Length > 1 && int.TryParse(parts[1], out var c) ? c : 0;

            if (Params.TryGetValue(parts[0], out var value) && component < value.Length)
            {
                MetallicOffsets[metal.Type] = value[component];
            }
        }

        if (BlendLayers.Count < 2)
        {
            return;
        }

        Dictionary<int, string>? groups = null;
        table?.TextureGroups.TryGetValue(ShaderName, out groups);

        foreach (MaterialBlendLayer layer in BlendLayers)
        {
            MaterialSampler? albedo = Samplers.Find(x => x.Type == layer.Albedo);
            if (albedo == null)
            {
                continue;
            }

            List<MaterialSampler> sameGroup = groups != null && groups.TryGetValue(albedo.Slot, out var group)
                ? metals.Where(m => groups.TryGetValue(m.Slot, out var g) && g == group).ToList()
                : [];

            List<MaterialSampler> sameNumber = metals.Where(m => m.Suffix == albedo.Suffix).ToList();

            layer.Metallic = sameGroup.Count == 1 ? sameGroup[0].Type
                : sameGroup.Count > 1 ? (sameGroup.Find(m => m.Suffix == albedo.Suffix) ?? sameGroup[0]).Type
                : sameNumber.Count == 1 ? sameNumber[0].Type
                : null;
        }
    }

    /// <summary>
    /// A material stays as it was if it doesn't give the strands a texture.
    /// Fur has no overlay or blended layers: these shaders only look like they do from their textures.
    /// </summary>
    private void ResolveFur(MaterialShaderTable? table)
    {
        MaterialFurRecipe? recipe = null;

        if (Surface != MaterialSurface.Standard || table == null || !table.Fur.TryGetValue(ShaderName, out recipe))
        {
            return;
        }

        MaterialSampler? strand = Samplers.Find(x => x.Slot == recipe.Cut && x.Path != "");

        MaterialSampler? InSlots(IEnumerable<int> slots, string role) =>
            slots.Select(s => Samplers.Find(x => x.Slot == s && x.Role == role && x.Path != "" && x != strand))
                .FirstOrDefault(x => x != null);

        if (strand == null)
        {
            return;
        }

        MaterialSampler? color = InSlots(recipe.FirstUvSlots, AlbedoRole);

        Surface = MaterialSurface.Fur;
        Detail = null;
        Blend = null;
        BlendLayers.Clear();
        BlendLayerCount = 1;
        BlendWeight = MaterialBlendWeight.Unknown;

        Fur = new MaterialResolvedFur
        {
            BaseType = color?.Type,
            StrandType = strand.Type,
            BaseNormalType = InSlots(recipe.FirstUvSlots, NormalRole)?.Type,
            StrandNormalType = recipe.ThirdUv ? InSlots(recipe.ThirdUvSlots, NormalRole)?.Type : null,
            MaskedType = recipe.Masked is int maskedSlot ? Samplers.Find(x => x.Slot == maskedSlot)?.Type : null,
            MaskType = recipe.Mask is int maskSlot ? Samplers.Find(x => x.Slot == maskSlot)?.Type : null,
            ThirdUv = recipe.ThirdUv,
            DitherWidth = Values("g_AlphaRef", [0, 0])[1] / 255f,
            Color = (strand.Color ?? color?.Color ?? [1, 1, 1]).Select(x => Math.Min(x, 1)).ToArray()
        };
    }

    /// <summary>
    /// The channels a layer's value can come from, and the flags on top of them.
    /// These are the values the fragment shader expects in its blend data.
    /// </summary>
    private static readonly Regex VertexSource = new(@"^TEXCOORD(\d+)\.([xyz])$", RegexOptions.Compiled);

    /// <summary>The TEXCOORD a vertex source reads (TEXCOORD5.x is 5), or null for a mask or color source</summary>
    private static int? VertexAttribute(string source) => VertexSource.Match(source) is { Success: true } m ? int.Parse(m.Groups[1].Value) : null;

    /// <summary>
    /// A vertex source of any TEXCOORD reads the vertex blend values: the viewport puts that attribute where TEXCOORD1
    /// is (BlendVertexAttribute, FlverResource.GetTexCoordIndex), so TEXCOORD5.x is the same channel as TEXCOORD1.x
    /// </summary>
    private static uint? BlendSource(MaterialBlendRecipeLayer layer)
    {
        uint? channel = layer.Source switch
        {
            "Mask.r" => 0,
            "Mask.g" => 1,
            "Mask.b" => 2,
            "COLOR1.x" => 6,
            // Snow: the facing value, in place of a channel (MaterialResolvedBlend.SourceFacing)
            "FACING" => 0,
            var s when VertexSource.Match(s) is { Success: true } m => 3u + (uint)(m.Groups[2].Value[0] - 'x'),
            _ => null
        };

        return channel | (layer.Invert ? 8u : 0u) | (layer.Soft ? 16u : 0u);
    }

    /// <summary>
    /// Replaces the layers worked out from the names of the textures with the ones the shader really uses.
    /// A material stays as it was if the recipe asks for a layer it can't provide.
    /// </summary>
    private void ResolveBlendRecipe(MaterialShaderTable? table)
    {
        var staticSwitch = (int)GetFirst("GXFT_SATStaticSwitch", 0);

        MaterialBlendRecipe? recipe = null;
        foreach (var key in new[] { $"{ShaderName}@{staticSwitch}", $"{ShaderName}@0", ShaderName })
        {
            if (table != null && table.Blends.TryGetValue(key, out recipe))
            {
                break;
            }
        }

        if (recipe == null)
        {
            return;
        }

        var layers = recipe.Layers.Take(MaterialResolvedBlend.MaxWeighted).ToList();
        if (layers.Count == 0 || layers.Any(x => BlendSource(x) == null))
        {
            return;
        }

        // The vertex sources can read two attributes: the first goes where TEXCOORD1 is, the second where TEXCOORD2 is,
        // of which only x is passed on (AC6's [MS] blends read TEXCOORD1.xy and TEXCOORD5.x). TEXCOORD1 is the first if
        // the recipe reads it
        var attributes = layers.Select(x => VertexAttribute(x.Source)).Where(x => x != null).Select(x => x!.Value)
            .Distinct().OrderBy(x => x == 1 ? 0 : 1).ThenBy(x => x).ToList();
        if (attributes.Count > 2
            || (attributes.Count == 2 && layers.Any(x => VertexAttribute(x.Source) == attributes[1] && !x.Source.EndsWith(".x"))))
        {
            return;
        }

        string? TypeOf(int? slot) => slot is null or < 0 ? null : Samplers.Find(x => x.Slot == slot)?.Type;

        // A layer with no albedo (-1) is the color of its param, as some of AC6's [MS] layers are
        bool ColorOnly(MaterialBlendRecipeLayer x) => x.Albedo < 0 && x.Color != null;

        var bottom = TypeOf(recipe.Albedo);
        if (bottom == null || layers.Any(x => TypeOf(x.Albedo) == null && !ColorOnly(x)))
        {
            return;
        }

        BlendVertexAttribute = attributes.Count >= 1 ? attributes[0] : 1;
        BlendVertexAttribute2 = attributes.Count == 2 ? attributes[1] : 0;

        MaterialResolvedBlend blend = new()
        {
            MaskType = TypeOf(recipe.Mask),
            DetailType = TypeOf(recipe.DetailMask),
            Scale = recipe.Scale,
            DetailBias = recipe.DetailBias
        };

        BlendLayers = [new MaterialBlendLayer { Albedo = bottom, Normal = TypeOf(recipe.Normal) }];
        blend.Tints[0] = LayerTint(recipe.AlbedoColor);

        for (var i = 0; i < layers.Count; i++)
        {
            MaterialBlendRecipeLayer layer = layers[i];

            BlendLayers.Add(new MaterialBlendLayer { Albedo = TypeOf(layer.Albedo), Normal = TypeOf(layer.Normal), ColorOnly = ColorOnly(layer) });
            blend.Sharpness[i] = layer.Sharpness == null ? 0 : EvaluateProduct(layer.Sharpness);
            blend.Detail[i] = layer.Detail == null ? 0 : EvaluateProduct(layer.Detail);
            blend.Sources[i] = BlendSource(layer)!.Value;
            blend.Tints[i + 1] = LayerTint(layer.Color);

            // The second attribute's x is channel 7 (FlverShader.frag, fsin_vertexBlend.w)
            if (BlendVertexAttribute2 != 0 && VertexAttribute(layer.Source) == BlendVertexAttribute2)
            {
                blend.Sources[i] = (blend.Sources[i] & ~MaterialResolvedBlend.ChannelMask) | 7u;
            }

            if (layer.IsExtended)
            {
                blend.Extended = true;
                blend.Sources[i] |= MaterialResolvedBlend.SourceExtended;
                blend.LayerChannels[i] = layer.DetailChannels!.Take(4).Select(EvaluateSum).Concat(new float[4]).Take(4).ToArray();
                blend.LayerBias[i] = layer.DetailBias == null ? 0 : EvaluateSum(layer.DetailBias);
                blend.LayerSoftScale[i] = layer.SoftScale == null ? 1 : EvaluateSum(layer.SoftScale);
                blend.LayerDetailTypes[i] = TypeOf(layer.DetailMask);

                // Where the game samples the layer's detail mask with the second UV set
                if (Samplers.Find(x => x.Slot == layer.DetailMask)?.UvSet == 1)
                {
                    blend.Sources[i] |= MaterialResolvedBlend.SourceDetailSecondUv;
                }
            }
        }

        ResolveColorAdjust(recipe, layers, blend);

        Blend = blend;
        BlendLayerCount = BlendLayers.Count;
        BlendWeight = MaterialBlendWeight.Recipe;
    }

    /// <summary>
    /// The [MbN_ColorAdjust] form (MaterialBlendRecipeLayer.AddSource and on). Its values go in the entries the extended
    /// form uses, so a recipe with an extended layer is left as it is
    /// </summary>
    private void ResolveColorAdjust(MaterialBlendRecipe recipe, List<MaterialBlendRecipeLayer> layers, MaterialResolvedBlend blend)
    {
        if (blend.Extended)
        {
            return;
        }

        bool IsSet(string? flag) => flag != null && EvaluateProduct(flag) != 0;
        float Adjust(string? strength, string? flag) => strength != null && IsSet(flag) ? Math.Clamp(EvaluateProduct(strength), 0, 1) : -1;

        blend.ColorAdjust[0] = Adjust(recipe.AlbedoColorAdjust, recipe.AlbedoColorAdjustIf);

        for (var i = 0; i < layers.Count; i++)
        {
            MaterialBlendRecipeLayer layer = layers[i];
            blend.ColorAdjust[i + 1] = Adjust(layer.ColorAdjust, layer.ColorAdjustIf);

            if (layer.HardMix != null)
            {
                blend.LayerHardMix[i] = EvaluateProduct(layer.HardMix);
                blend.Sources[i] |= MaterialResolvedBlend.SourceMixed;
            }

            if (layer.WeightScale != null)
            {
                blend.LayerWeightScale[i] = EvaluateProduct(layer.WeightScale);
                blend.Sources[i] |= MaterialResolvedBlend.SourceScaled;
            }

            if (layer.DetailBiasOverride is float bias)
            {
                blend.LayerBiasOverride[i] = bias;
                blend.Sources[i] |= MaterialResolvedBlend.SourceBias;
            }

            // Snow: the facing value, with its vertex value's channel (3-5, TEXCOORD1's) above SourceFacingShift
            if (layer.Source == "FACING")
            {
                blend.Sources[i] |= MaterialResolvedBlend.SourceFacing;
                blend.LayerFacingBias[i] = layer.FacingBias == null ? 0 : EvaluateProduct(layer.FacingBias);
                if (layer.FacingDirection != null && Params.TryGetValue(layer.FacingDirection, out var direction) && direction.Length >= 3)
                {
                    blend.FacingDirection = direction[..3];
                }

                if (layer.FacingVertex != null && VertexSource.Match(layer.FacingVertex) is { Success: true } fv && int.Parse(fv.Groups[1].Value) == BlendVertexAttribute)
                {
                    blend.Sources[i] |= (3u + (uint)(fv.Groups[2].Value[0] - 'x')) << MaterialResolvedBlend.SourceFacingShift;
                }
            }

            // Only a value of the attribute the vertex blend values already come from
            if (layer.AddSource != null && VertexSource.Match(layer.AddSource) is { Success: true } add
                && int.Parse(add.Groups[1].Value) == BlendVertexAttribute)
            {
                var channel = 3u + (uint)(add.Groups[2].Value[0] - 'x');
                blend.Sources[i] |= MaterialResolvedBlend.SourceAdd | (channel << MaterialResolvedBlend.SourceAddShift);
            }

            if (layer.ScaleSource == "COLOR1.w" && IsSet(layer.ScaleIf))
            {
                blend.Sources[i] |= MaterialResolvedBlend.SourceScaleAlpha;
            }
        }

        blend.Adjusted = layers.Any(x => x.HardMix != null || x.AddSource != null || x.WeightScale != null || x.DetailBiasOverride != null || x.Source == "FACING")
            || blend.ColorAdjust.Any(x => x >= 0);
    }

    /// <summary>
    /// An overlay only counts if the material gives it a texture, and if not the overlay is left out altogether.
    /// </summary>
    private void ResolveDetailRecipe(MaterialShaderTable? table)
    {
        var staticSwitch = (int)GetFirst("GXFT_SATStaticSwitch", 0);

        MaterialDetailRecipe? recipe = null;
        foreach (var key in new[] { $"{ShaderName}@{staticSwitch}", $"{ShaderName}@0", ShaderName })
        {
            if (table != null && table.Details.TryGetValue(key, out recipe))
            {
                break;
            }
        }

        if (recipe == null)
        {
            return;
        }

        // The file can be the material's or the model's, which isn't known here. The viewport looks for both
        // (FlverResource.LoadBlendRecipe), and the shader leaves out an overlay whose texture isn't there
        string? TypeOf(int? slot) => slot == null ? null : Samplers.Find(x => x.Slot == slot)?.Type;

        MaterialResolvedDetail detail = new()
        {
            AlbedoType = TypeOf(recipe.Albedo),
            Color = LayerTint(recipe.Color),
            Overlay = recipe.AlbedoBlend == "Overlay",
            OverlayStrength = recipe.AlbedoStrength == null ? 0 : EvaluateProduct(recipe.AlbedoStrength),
            NormalType = TypeOf(recipe.Normal),
            NormalStrength = recipe.NormalStrength == null ? 0 : EvaluateProduct(recipe.NormalStrength),
            BaseColor = recipe.BaseColor != null && Params.TryGetValue(recipe.BaseColor, out var baseColor) && baseColor.Length >= 3 ? baseColor[..3] : null
        };

        // A stack needs its weight map, unless every layer weighs itself by its own alpha; without one the bottom
        // detail is drawn alone, as before
        var weightType = TypeOf(recipe.StackWeightMap);
        if (recipe.Stack is { Count: > 0 } && (weightType != null || recipe.Stack.All(x => x.OwnAlpha == true)))
        {
            detail.StackWeightType = weightType;
            foreach (MaterialDetailStackLayer layer in recipe.Stack.Take(MaterialResolvedDetail.MaxStackLayers))
            {
                detail.Stack.Add(new MaterialResolvedDetailLayer
                {
                    AlbedoType = TypeOf(layer.Albedo),
                    NormalType = TypeOf(layer.Normal),
                    Color = LayerTint(layer.Color),
                    Channel = Math.Max(0, "rgba".IndexOf(layer.Channel, StringComparison.Ordinal)),
                    Scale = EvaluateSum(layer.Scale),
                    Bias = EvaluateSum(layer.Bias),
                    Power = layer.Power,
                    Invert = layer.Invert == true,
                    Replace = layer.Replace == true,
                    OwnAlpha = layer.OwnAlpha == true
                });
            }

            // Nothing of the stack is given a texture: it is the bottom detail alone
            if (detail.Stack.All(x => x.AlbedoType == null && x.NormalType == null))
            {
                detail.Stack.Clear();
                detail.StackWeightType = null;
            }
        }

        detail.BackAlbedoType = TypeOf(recipe.BackAlbedo);
        detail.BackNormalType = TypeOf(recipe.BackNormal);
        detail.BackColor = LayerTint(recipe.BackColor);

        if (detail.AlbedoType != null || detail.NormalType != null || detail.HasStackEntries)
        {
            Detail = detail;
        }
    }

    private void ResolveSurface()
    {
        var flame = FlameShader.IsMatch(ShaderName);

        if (flame || UnlitShader.IsMatch(ShaderName))
        {
            Surface = MaterialSurface.Unlit;
        }
        else if (WaterShader.IsMatch(ShaderName))
        {
            Surface = MaterialSurface.Water;
        }
        else
        {
            return;
        }

        if (flame)
        {
            BlendMode = BlendModeAdd;
            DisableDepthWrite = true;
        }

        // The texture that moves is the one that matters. These shaders don't name their textures reliably
        List<MaterialSampler> textures = Samplers.Where(x => x.Path != "").ToList();
        var named = Surface == MaterialSurface.Water ? NormalRole : AlbedoRole;

        SurfaceType = (textures.Find(x => x.Role == named)
            ?? textures.Find(x => x.Scroll.Any(v => v != 0))
            ?? textures.FirstOrDefault())?.Type;
    }

    /// <summary>
    /// Works out the two sets of ripples and the color of water. Without a recipe, the one
    /// texture goes the other way at another size, so that it doesn't look like a sliding picture.
    /// </summary>
    private void ResolveWater(MaterialShaderTable? table)
    {
        if (Surface != MaterialSurface.Water)
        {
            return;
        }

        MaterialWaterRecipe? recipe = null;
        table?.Water.TryGetValue(ShaderName, out recipe);

        List<MaterialWaterLayer> normals = (recipe?.Layers ?? [])
            .Where(x => Samplers.Exists(s => s.Slot == x.Slot && s.Role == NormalRole && s.Path != ""))
            .ToList();

        MaterialSampler? SamplerOf(MaterialWaterLayer layer) => Samplers.Find(x => x.Slot == layer.Slot && x.Role == NormalRole);

        float[] ScaleOf(MaterialWaterLayer layer) => Values(layer.Scale, [1, 1]).Select(x => x != 0 ? x : 1).ToArray();

        float[] ScrollOf(MaterialWaterLayer layer)
        {
            var time = layer.Time != null ? GetFirst(layer.Time, 1) : 1;
            return Values(layer.Scroll, [0, 0]).Select(x => x * time).ToArray();
        }

        if (normals.Count > 0)
        {
            MaterialSampler main = SamplerOf(normals[0])!;
            float[] scale = ScaleOf(normals[0]);
            float[] scroll = ScrollOf(normals[0]);

            main.Tiling = [main.Tiling[0] * scale[0], main.Tiling[1] * scale[1]];
            main.Scroll = [scroll[0] / scale[0], scroll[1] / scale[1]];
            SurfaceType = main.Type;
        }

        MaterialResolvedWater water = new()
        {
            Gloss = recipe?.Gloss != null ? MathF.Sqrt(Math.Clamp(GetFirst(recipe.Gloss, 1), 0, 1)) * 0.95f : DefaultGloss,
            HasVolume = !Samplers.Exists(x => x.Role == AlbedoRole && x.Path != ""),
            Scatter = recipe?.Scatter != null ? Values(recipe.Scatter, [0, 0, 0]) : DefaultScatter,
            Absorption = recipe?.Absorption != null ? Values(recipe.Absorption, [0, 0, 0]) : DefaultAbsorption,
            Tint = LayerTint(recipe?.Tint),
            EdgeFade = 1
        };

        var fade = recipe?.EdgeFade != null ? EvaluateProduct(recipe.EdgeFade) : 0;
        var distance = recipe?.EdgeDistance != null ? EvaluateProduct(recipe.EdgeDistance) : 0;

        if (fade > 0)
        {
            water.EdgeFade = fade;
        }
        else if (distance > 0)
        {
            water.EdgeFade = 1 / distance;
        }

        if (normals.Count > 1)
        {
            MaterialSampler detail = SamplerOf(normals[1])!;
            float[] scale = ScaleOf(normals[1]);
            float[] scroll = ScrollOf(normals[1]);
            float[] bend = Values(recipe?.Bend, [0, 0]);

            water.DetailType = detail.Type;
            water.DetailTiling = [detail.Tiling[0] * scale[0], detail.Tiling[1] * scale[1]];

            // The shader adds these to UVs which are already scaled
            water.DetailScroll = [scroll[0] / scale[0], scroll[1] / scale[1]];
            water.DetailBend = [bend[0] * 0.4f / scale[0], bend[1] * 0.4f / scale[1]];
            water.DetailStrength = normals[1].Strength != null ? GetFirst(normals[1].Strength!, 1) : 1;
        }
        else if (Samplers.Find(x => x.Type == SurfaceType) is { } single)
        {
            water.DetailType = single.Type;
            water.DetailTiling = [single.Tiling[0] * 1.37f, single.Tiling[1] * 1.37f];
            water.DetailScroll = [single.Scroll[0] * -0.7f / 1.37f, single.Scroll[1] * -0.7f / 1.37f];
            water.DetailStrength = 0.5f;
        }

        Water = water;
    }

    private float[] Values(string? param, float[] fallback)
    {
        return param != null && Params.TryGetValue(param, out var value) && value.Length >= fallback.Length
            ? value[..fallback.Length]
            : fallback;
    }

    /// <summary>The glow is left out if the material doesn't give it a texture</summary>
    private void ResolveMagmaRecipe(MaterialShaderTable? table)
    {
        var staticSwitch = (int)GetFirst("GXFT_SATStaticSwitch", 0);

        MaterialMagmaRecipe? recipe = null;
        foreach (var key in new[] { $"{ShaderName}@{staticSwitch}", $"{ShaderName}@0", ShaderName })
        {
            if (table != null && table.Magma.TryGetValue(key, out recipe))
            {
                break;
            }
        }

        var type = recipe == null ? null : Samplers.Find(x => x.Slot == recipe.Texture && x.Path != "")?.Type;

        if (recipe == null || type == null)
        {
            return;
        }

        Magma = new MaterialResolvedMagma
        {
            TextureType = type,
            RedSample = recipe.RedSample,
            Color = Values(recipe.Color, [0, 0, 0]),
            Power = GetFirst(recipe.Power, 1),
            Strength = GetFirst(recipe.Strength, 1),
            Distort = Values(recipe.Distort, [0, 0]),
            Scroll0 = Values(recipe.Scroll0, [0, 0]),
            Scale0 = Values(recipe.Scale0, [1, 1]),
            Scroll1 = Values(recipe.Scroll1, [0, 0]),
            Scale1 = Values(recipe.Scale1, [1, 1]),
            Limit = recipe.Limit
        };
    }

    private float[] LayerTint(string? param)
    {
        return param != null && Params.TryGetValue(param, out var color) && color.Length >= 3
            ? color[..3].Select(x => Math.Min(x, 1)).ToArray()
            : [1, 1, 1];
    }

    private void ApplyShaderEntry(MaterialShaderEntry entry)
    {
        IsKnownShader = true;
        Deformer = entry.Deformer;
        BlendWeight = entry.BlendWeight;

        foreach ((var role, var param) in entry.Params)
        {
            if (Params.TryGetValue(param, out var value))
            {
                DeformerParams[role] = value;
            }
        }

        foreach ((var role, var slot) in entry.Textures)
        {
            MaterialSampler? sampler = Samplers.Find(x => x.Slot == slot);
            if (sampler != null)
            {
                DeformerTextures[role] = sampler.Path;
            }
        }
    }

    /// <summary>
    /// Works out which albedo and normal belong to each layer of a [MbN] shader.
    /// The numbers in the names can't be used as layer indices directly: depending on the shader they
    /// start at 0 or 1, and can even repeat (M[Flag][Mb2] has AlbedoMap_0 twice). A shader can also have
    /// normals that aren't layers, such as the overlay normal of [Ov_N], so the number of layers
    /// comes from the shader name, and normals are only taken if they are numbered.
    /// </summary>
    private void ResolveBlendLayers()
    {
        foreach (var token in ShaderTokens)
        {
            Match match = BlendToken.Match(token);
            if (match.Success)
            {
                BlendLayerCount = match.Groups[1].Value[0] - '0';
                break;
            }
        }

        if (BlendLayerCount < 2)
        {
            return;
        }

        List<MaterialSampler> albedos = OrderedLayerSamplers(AlbedoRole).Take(BlendLayerCount).ToList();
        List<MaterialSampler> normals = OrderedLayerSamplers(NormalRole).ToList();

        // Prefer the normal with the same number as its albedo. If none line up, go by position
        var matchBySuffix = albedos.Count > 0 && albedos.All(a => normals.Exists(n => n.Suffix == a.Suffix))
            && albedos.Select(a => a.Suffix).Distinct().Count() == albedos.Count;

        for (var i = 0; i < albedos.Count; i++)
        {
            MaterialSampler? normal = matchBySuffix
                ? normals.Find(n => n.Suffix == albedos[i].Suffix)
                : i < normals.Count ? normals[i] : null;

            BlendLayers.Add(new MaterialBlendLayer { Albedo = albedos[i].Type, Normal = normal?.Type });
        }
    }

    /// <summary>
    /// A sampler's own scale wins if it has one. Otherwise it takes the scale of its UV group.
    /// </summary>
    private void ResolveTiling(MaterialShaderTable? table)
    {
        Dictionary<int, string>? groups = null;
        table?.TextureGroups.TryGetValue(ShaderName, out groups);

        foreach (MaterialSampler sampler in Samplers)
        {
            if (sampler.Scale.Length >= 2 && (sampler.Scale[0] != 0 || sampler.Scale[1] != 0))
            {
                sampler.Tiling = sampler.Scale[..2];
            }
            else if (groups != null && groups.TryGetValue(sampler.Slot, out var group)
                && Params.TryGetValue($"{group}_CommonUV-UVParam", out var scale)
                && scale.Length >= 2 && scale[0] != 0 && scale[1] != 0)
            {
                sampler.Tiling = scale[..2];
            }
        }
    }

    private void ResolveTextureInputs(MaterialShaderTable? table)
    {
        // Static switches change which textures a shader tints, and only the common ones are in the table.
        // Materials on any other fall back on the first, where the main textures are treated the same
        var staticSwitch = (int)GetFirst("GXFT_SATStaticSwitch", 0);

        List<Dictionary<int, MaterialTextureInput>> candidates = new();
        foreach (var key in new[] { $"{ShaderName}@{staticSwitch}", $"{ShaderName}@0", ShaderName })
        {
            if (table != null && table.TextureInputs.TryGetValue(key, out var found))
            {
                candidates.Add(found);
            }
        }

        // MTD shaders scroll a whole UV set, and always the first here
        Params.TryGetValue("g_TexScroll_0", out var uvSetScroll);

        foreach (MaterialSampler sampler in Samplers)
        {
            if (uvSetScroll != null && uvSetScroll.Length >= 2)
            {
                sampler.Scroll = uvSetScroll[..2];
            }

            MaterialTextureInput? input = candidates
                .Select(x => x.GetValueOrDefault(sampler.Slot))
                .FirstOrDefault(x => x != null);

            if (input == null)
            {
                continue;
            }

            if (input.Color != null && Params.TryGetValue(input.Color, out var color) && color.Length >= 3)
            {
                sampler.Color = color[..3];

                if (input.Factor != null)
                {
                    var factor = EvaluateProduct(input.Factor);
                    sampler.Color = sampler.Color.Select(x => x * factor).ToArray();
                }

                // Color parameters are RGB, alpha and intensity. The intensity is for light given off
                if (sampler.Role == EmissiveRole && color.Length >= 5)
                {
                    sampler.Color = sampler.Color.Select(x => x * color[4]).ToArray();
                }
            }

            if (input.ScrollU != null && input.ScrollV != null)
            {
                sampler.Scroll = [EvaluateProduct(input.ScrollU), EvaluateProduct(input.ScrollV)];
            }
        }
    }

    /// <summary>
    /// Multiplies out a <see cref="MaterialTextureInput"/> expression, where a parameter
    /// the material doesn't set is 0, which is what the shader's constant would hold.
    /// </summary>
    /// <summary>A sum of products ("2*snp_0_float_52_0 + -1"), as the extended blend form writes its values</summary>
    private float EvaluateSum(string expression)
    {
        return expression.Split(" + ").Sum(term => EvaluateProduct(term.Trim()));
    }

    private float EvaluateProduct(string expression)
    {
        var result = 1.0f;

        foreach (var factor in expression.Split('*'))
        {
            if (float.TryParse(factor, CultureInfo.InvariantCulture, out var number))
            {
                result *= number;
                continue;
            }

            Match component = SuffixName.Match(factor);
            if (component.Success && Params.TryGetValue(component.Groups[1].Value, out var value)
                && int.Parse(component.Groups[2].Value) < value.Length)
            {
                result *= value[int.Parse(component.Groups[2].Value)];
            }
            else if (Params.TryGetValue(factor, out var whole) && whole.Length > 0)
            {
                result *= whole[0];
            }
            else
            {
                return 0;
            }
        }

        return result;
    }

    private IEnumerable<MaterialSampler> OrderedLayerSamplers(string role)
    {
        return Samplers.Where(x => x.Role == role && x.Suffix >= 0).OrderBy(x => x.Suffix).ThenBy(x => x.Slot);
    }

    private float GetFirst(string name, float fallback)
    {
        return Params.TryGetValue(name, out var value) && value.Length > 0 ? value[0] : fallback;
    }

    /// <summary>
    /// Strips the shader prefix: M_Flag__Mb2__snp_0_float_20 becomes snp_0_float_20.
    /// </summary>
    private static string ShortParamName(string name)
    {
        var index = name.IndexOf("snp_", StringComparison.Ordinal);
        return index > 0 ? name[index..] : name;
    }

    private static MaterialSampler ParseSampler(string type, string path, float[] scale)
    {
        MaterialSampler sampler = new() { Type = type, Path = path, Scale = scale };

        var role = type;

        Match slot = SlotName.Match(type);
        if (slot.Success)
        {
            sampler.Slot = int.Parse(slot.Groups[1].Value);
            role = slot.Groups[2].Value;
        }

        if (role.StartsWith("GSBlendMap", StringComparison.Ordinal))
        {
            role = role["GSBlendMap".Length..];
        }

        role = role.TrimStart('_');

        Match suffix = SuffixName.Match(role);
        if (suffix.Success)
        {
            role = suffix.Groups[1].Value;
            sampler.Suffix = int.Parse(suffix.Groups[2].Value);
        }

        sampler.Role = role;
        return sampler;
    }

    private static float[] ToFloats(object? value)
    {
        return value switch
        {
            bool b => [b ? 1 : 0],
            int i => [i],
            float f => [f],
            int[] ints => ints.Select(x => (float)x).ToArray(),
            float[] floats => floats,
            _ => []
        };
    }
