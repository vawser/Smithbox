public class MaterialBlendRecipeLayer
{
    public int Albedo { get; set; }
    public int? Normal { get; set; }
    public string? Color { get; set; }

    /// <summary>Mask.r/g/b, or a vertex attribute such as TEXCOORD1.x</summary>
    public string Source { get; set; } = "";

    /// <summary>The value is one minus the source</summary>
    public bool Invert { get; set; }

    /// <summary>
    /// Uses the shader's other weight: saturate(value - sharpness * (1 - value) * (detail + 0.01))
    /// </summary>
    public bool Soft { get; set; }

    /// <summary>A product for <see cref="MaterialDefinition"/> to evaluate, or null for 0</summary>
    public string? Sharpness { get; set; }
    public string? Detail { get; set; }

    // The extended form (AC6's [MS] blends), set by Tools/ShaderSignature where the recipe's own form doesn't fit.
    // The layer has a detail mask of its own, and its detail is sum_c DetailChannels[c] * mask.c + DetailBias, each a
    // sum of products ("2*snp_0_float_52_0 + -1"). A hard weight is then sat(1 - sharpness (2v - d)), with no Scale,
    // and a soft one sat((v - sharpness (1 - v)(d + 0.01)) * SoftScale)

    /// <summary>The slot of the layer's own detail mask</summary>
    public int? DetailMask { get; set; }

    /// <summary>What multiplies the detail mask's r, g, b and a, or null for the recipe's own form</summary>
    public string[]? DetailChannels { get; set; }

    public string? DetailBias { get; set; }

    /// <summary>What multiplies a soft weight, null for 1</summary>
    public string? SoftScale { get; set; }

    // The [MbN_ColorAdjust] form, merged in from Tools/ShaderSignature's coloradjust mode ({GAME}_ColorAdjust.json).
    // The value is sat(Source + AddSource), times ScaleSource where the ScaleIf bool is set, and the weight is
    // lerp(value, the hard weight of it, HardMix): with HardMix 1 it is the recipe's own weight

    /// <summary>A vertex value added to the source before it is saturated ("TEXCOORD1.x")</summary>
    public string? AddSource { get; set; }

    /// <summary>A vertex value the value is then multiplied by ("COLOR1.w"), where the <see cref="ScaleIf"/> bool is set</summary>
    public string? ScaleSource { get; set; }
    public string? ScaleIf { get; set; }

    /// <summary>The param that lerps from the value to the hard weight, null for the hard weight alone</summary>
    public string? HardMix { get; set; }

    /// <summary>A param the finished weight is multiplied by (M[Cave_001]'s snp_0_float_16), null for none</summary>
    public string? WeightScale { get; set; }

    /// <summary>The layer's detail bias where it isn't the recipe's <see cref="MaterialBlendRecipe.DetailBias"/></summary>
    public float? DetailBiasOverride { get; set; }

    // Snow ([Snow_VtxMask]), a Source of "FACING": the value is sat(FacingBias + dot(N, FacingDirection)), with N the
    // world normal of the bottom layer's normal map, times FacingVertex if there is one

    /// <summary>A float3 param, the direction surfaces facing which are covered ("snp_0_float3_0")</summary>
    public string? FacingDirection { get; set; }
    public string? FacingBias { get; set; }
    public string? FacingVertex { get; set; }

    /// <summary>
    /// Where the <see cref="ColorAdjustIf"/> bool is set, the albedo is lerp(texture, Color, ColorAdjust) in place of
    /// texture * Color
    /// </summary>
    public string? ColorAdjust { get; set; }
    public string? ColorAdjustIf { get; set; }

    [JsonIgnore]
    public bool IsExtended => DetailChannels != null;
}

