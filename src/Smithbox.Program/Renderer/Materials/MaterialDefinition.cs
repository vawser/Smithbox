/// <summary>
/// An overlay on top of a material: its albedo is multiplied by Albedo * 4.55 * Color, as those
/// textures average about 0.22, and the normal's offset from flat is added scaled by NormalStrength.
/// </summary>
public class MaterialDetailRecipe
{
    public int? Albedo { get; set; }
    public string? Color { get; set; }

    public int? Normal { get; set; }
    public string? NormalStrength { get; set; }

    /// <summary>The color parameter that is the albedo of a shader with no albedo texture</summary>
    public string? BaseColor { get; set; }

    /// <summary>
    /// "Overlay" for the [Ov_AN] form, where the overlay O is laid over the albedo A in gamma space by a strength s:
    /// x = A + s(g - 0.5)(O - A), then sat(x + s(0.5 - g)(O - x)), with g = O^0.454. Otherwise A is multiplied
    /// </summary>
    public string? AlbedoBlend { get; set; }

    /// <summary>The s of an "Overlay" <see cref="AlbedoBlend"/></summary>
    public string? AlbedoStrength { get; set; }

    /// <summary>
    /// C[DetailBlend]'s detail stack, generated by Tools/ShaderSignature's detailstacks mode ({GAME}_DetailStacks.json):
    /// further details lerped over this one, bottom first, before the result multiplies the albedo. Each weighs itself
    /// by a channel of <see cref="StackWeightMap"/>. The normals are lerped by the same weights
    /// </summary>
    public List<MaterialDetailStackLayer>? Stack { get; set; }

    /// <summary>The slot of the texture the stack's weights read (the base normal map's blue and alpha)</summary>
    public int? StackWeightMap { get; set; }

    /// <summary>
    /// What back faces are drawn with instead (C[DetailBlend] permutations 15 and up): the albedo is Color * BackAlbedo
    /// alone, and the base normal gets BackNormal's offset at a strength of 1 in place of the details'
    /// </summary>
    public int? BackAlbedo { get; set; }
    public string? BackColor { get; set; }
    public int? BackNormal { get; set; }
}

/// <summary>
/// One layer of a detail stack: lerped over the details below it by sat(pow(Scale * x + Bias, Power)), with x the
/// <see cref="Channel"/> of the stack's weight map. C[DetailBlend]'s weights are sat((b * 22)^260), a step at a
/// blue of 1/22, and sat((0.5 ± f(a - 0.5)) * 2.05 - 1.05), a ramp on the alpha
/// </summary>
public class MaterialDetailStackLayer
{
    public int? Albedo { get; set; }
    public string? Color { get; set; }
    public int? Normal { get; set; }

    /// <summary>r, g, b or a</summary>
    public string Channel { get; set; } = "a";

    /// <summary>Sums of products for <see cref="MaterialDefinition"/> to evaluate ("-2.05*snp_0_float_19_0")</summary>
    public string Scale { get; set; } = "1";
    public string Bias { get; set; } = "0";
    public float Power { get; set; } = 1;

    /// <summary>The layer takes one minus the weight: it was the bottom of its lerp</summary>
    public bool? Invert { get; set; }

    /// <summary>
    /// Lerped over the finished albedo (base * details * 4.55) rather than among the details, so it replaces the color.
    /// These come after the detail layers. The normal is still lerped among the details'
    /// </summary>
    public bool? Replace { get; set; }

    /// <summary>Weighed by its own albedo's alpha, as it is, not by the weight map ([S2]'s lerp(X, c7 T8, T8.a))</summary>
    public bool? OwnAlpha { get; set; }
}

