/// <summary>
/// How a material moves its vertices. Filled in from the per-game shader table.
/// </summary>
[JsonConverter(typeof(JsonStringEnumConverter<MaterialDeformer>))]
public enum MaterialDeformer
{
    None,

    /// <summary>Plays a baked vertex animation texture, one column per vertex and one row per frame</summary>
    Vat,

    /// <summary>Offsets vertices along a direction by a smoothed triangle wave</summary>
    Sway,

    /// <summary>Bends vertices over in the direction of the wind, by a strength stored per vertex</summary>
    WindBend,

    /// <summary>Rotates vertices around a pivot stored per vertex, towards the wind</summary>
    WindPivot,

    /// <summary>The same as <see cref="Vat"/>, with the column one TEXCOORD earlier and no strength per vertex</summary>
    VatLoop,

    /// <summary>Rotates vertices back and forth around a pivot stored per vertex</summary>
    Swing,

    /// <summary>Flaps by a vertex animation while flying around an ellipse</summary>
    Birds,

    /// <summary>Leans around a pivot stored per vertex, and moves by a wave with its phase from a noise texture</summary>
    DirectionalWave
}

/// <summary>
/// Shaders that can't be translated, as they rely on the game's scene: the depth buffer, a water
/// simulation and the time of day. These stand in for them. The values are what the shaders read.
/// </summary>
public enum MaterialSurface
{
    Standard,

    /// <summary>Sky, clouds and flames: the texture as it is, with no lighting</summary>
    Unlit,

    /// <summary>A smooth surface with moving ripples</summary>
    Water,

    /// <summary>Cards of strands, cut out by a texture on top of the color of the character</summary>
    Fur
}

/// <summary>
/// Where the blend weight of a layered material comes from.
/// </summary>
[JsonConverter(typeof(JsonStringEnumConverter<MaterialBlendWeight>))]
public enum MaterialBlendWeight
{
    /// <summary>The layer weights are not known for this shader</summary>
    Unknown,

    /// <summary>The first component of the TEXCOORD1 vertex attribute</summary>
    TexCoord1X,

    /// <summary>Worked out in the shader from a <see cref="MaterialBlendRecipe"/></summary>
    Recipe
}

/// <summary>
/// How a material's color combines with what is behind it.
/// </summary>
public enum MaterialBlending
{
    Opaque,
    Alpha,
    Add,
    Subtract
}

/// <summary>
/// The per-game table of what is known about each shader. The numbered parameters of a shader
/// (such as snp_0_float_0) only have a meaning within that shader, so they are looked up here.
/// </summary>
public class MaterialShaderTable
{
    public Dictionary<string, MaterialShaderEntry> Shaders { get; set; } = new();

    /// <summary>
    /// Shader name to texture slot to UV group, generated from the game's shaders by the
    /// Material Definition Dumper. Materials give the tiling of a group, not of a texture.
    /// </summary>
    [JsonIgnore]
    public Dictionary<string, Dictionary<int, string>> TextureGroups { get; set; } = new();

    /// <summary>
    /// Shader name to texture slot to what the shader does to that texture,
    /// generated by analysing the game's compiled pixel shaders.
    /// </summary>
    [JsonIgnore]
    public Dictionary<string, Dictionary<int, MaterialTextureInput>> TextureInputs { get; set; } = new();

    /// <summary>
    /// Shader name to how it blends its layers, generated by analysing the game's compiled pixel shaders.
    /// </summary>
    [JsonIgnore]
    public Dictionary<string, MaterialBlendRecipe> Blends { get; set; } = new();

    /// <summary>
    /// Shader name to the overlay it puts on top of its layers, generated by analysing the game's compiled pixel shaders.
    /// </summary>
    [JsonIgnore]
    public Dictionary<string, MaterialDetailRecipe> Details { get; set; } = new();

    /// <summary>
    /// Shader name to the glow of a [magma] shader, generated by analysing the game's compiled pixel shaders.
    /// </summary>
    [JsonIgnore]
    public Dictionary<string, MaterialMagmaRecipe> Magma { get; set; } = new();

    /// <summary>
    /// Shader name to how it moves its ripples and colors its volume, generated by analysing the game's compiled pixel shaders.
    /// </summary>
    [JsonIgnore]
    public Dictionary<string, MaterialWaterRecipe> Water { get; set; } = new();

    /// <summary>
    /// Shader name to which of its textures make up its strands, generated by analysing the game's compiled pixel shaders.
    /// </summary>
    [JsonIgnore]
    public Dictionary<string, MaterialFurRecipe> Fur { get; set; } = new();

    /// <summary>
    /// Shader name to texture slot to the param added to the red of that metallic map before it is saturated,
    /// as "param:component" ("" for none), generated from the game's compiled pixel shaders by Tools/ShaderSignature.
    /// </summary>
    [JsonIgnore]
    public Dictionary<string, Dictionary<int, string>> Metallic { get; set; } = new();

    /// <summary>
    /// Shader name to texture slot to the UV set ("0" or "1") the game's shader samples it with,
    /// generated from the compiled pixel shaders by Tools/ShaderSignature. Slots sampled with both are left out.
    /// </summary>
    [JsonIgnore]
    public Dictionary<string, Dictionary<int, string>> UvSets { get; set; } = new();

    /// <summary>
    /// Shader name (or name@permutation) to the texture whose red is its glow, generated by Tools/ShaderSignature's
    /// emissivemasks mode ({GAME}_EmissiveMasks.json)
    /// </summary>
    [JsonIgnore]
    public Dictionary<string, MaterialEmissiveMask> EmissiveMasks { get; set; } = new();

    /// <summary>
    /// Adds the overlays found by Tools/ShaderSignature's overlays mode ({GAME}_Overlays.json) where the checked-in
    /// <see cref="Details"/> has none, or has no albedo for one: the [Ov_AN] albedo overlay was beyond what made those.
    /// </summary>
    /// <summary>
    /// Adds the blend recipes made by Tools/ShaderSignature's blends mode ({GAME}_GeneratedBlends.json) for the shaders
    /// <see cref="Blends"/> has none for. The checked-in ones win: the generator reproduces most of them, not all.
    /// </summary>
    public void MergeBlends(Dictionary<string, MaterialBlendRecipe> generated)
    {
        foreach (var (key, recipe) in generated)
        {
            Blends.TryAdd(key, recipe);
        }
    }

    /// <summary>
    /// Puts in the detail stacks made by Tools/ShaderSignature's detailstacks mode ({GAME}_DetailStacks.json). These
    /// replace the checked-in entry of their permutation: a stack's bottom detail is not always the one that names
    /// (C[DetailBlend]@1 lerps slot 1 over slot 2), and the generator carries the normal strength over.
    /// </summary>
    public void MergeDetailStacks(Dictionary<string, MaterialDetailRecipe> stacks)
    {
        foreach (var (key, stack) in stacks)
        {
            Details[key] = stack;
        }
    }

    /// <summary>
    /// Adds the [MbN_ColorAdjust] form found by Tools/ShaderSignature's coloradjust mode ({GAME}_ColorAdjust.json) to the
    /// blend recipes of the same key, by albedo slot. The recipes keep their own weights: these only add to them
    /// </summary>
    public void MergeColorAdjust(Dictionary<string, MaterialColorAdjustRecipe> adjusts)
    {
        foreach (var (key, adjust) in adjusts)
        {
            if (!Blends.TryGetValue(key, out MaterialBlendRecipe? recipe))
            {
                continue;
            }

            if (adjust.Layers.TryGetValue(recipe.Albedo, out MaterialBlendRecipeLayer? bottom))
            {
                recipe.AlbedoColorAdjust = bottom.ColorAdjust;
                recipe.AlbedoColorAdjustIf = bottom.ColorAdjustIf;
            }

            foreach (MaterialBlendRecipeLayer layer in recipe.Layers)
            {
                if (!adjust.Layers.TryGetValue(layer.Albedo, out MaterialBlendRecipeLayer? extra))
                {
                    continue;
                }

                layer.AddSource = extra.AddSource;
                layer.ScaleSource = extra.ScaleSource;
                layer.ScaleIf = extra.ScaleIf;
                layer.HardMix = extra.HardMix;
                layer.ColorAdjust = extra.ColorAdjust;
                layer.ColorAdjustIf = extra.ColorAdjustIf;
            }
        }
    }

    /// <summary>
    /// Adds the masked layers found by Tools/ShaderSignature's furmasks mode ({GAME}_FurMasks.json) to the fur recipes
    /// </summary>
    public void MergeFurMasks(Dictionary<string, MaterialFurMask> masks)
    {
        foreach (var (key, mask) in masks)
        {
            if (Fur.TryGetValue(key, out MaterialFurRecipe? fur))
            {
                fur.Masked = mask.Strands;
                fur.Mask = mask.Mask;
            }
        }
    }

    public void MergeOverlays(Dictionary<string, MaterialDetailRecipe> overlays)
    {
        foreach (var (key, overlay) in overlays)
        {
            if (!Details.TryGetValue(key, out MaterialDetailRecipe? detail))
            {
                Details[key] = overlay;
                continue;
            }

            if (detail.Albedo == null && overlay.Albedo != null)
            {
                detail.Albedo = overlay.Albedo;
                detail.AlbedoBlend = overlay.AlbedoBlend;
                detail.AlbedoStrength = overlay.AlbedoStrength;
            }

            if (detail.Normal == null && overlay.Normal != null)
            {
                detail.Normal = overlay.Normal;
                detail.NormalStrength = overlay.NormalStrength;
            }
        }
    }
}

/// <summary>
