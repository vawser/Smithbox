/// <summary>
/// A glow that is one texture's red, tinted: M[Crystal]'s Mask1Map.r * color_0 * f3. Generated by Tools/ShaderSignature's
/// emissivemasks mode ({GAME}_EmissiveMasks.json). The texture is drawn as the emissive, its red for all three channels
/// </summary>
public class MaterialEmissiveMask
{
    public int Slot { get; set; }
