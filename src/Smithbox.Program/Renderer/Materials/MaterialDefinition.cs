    /// <summary>What multiplies the texture, or null if the shader doesn't tint it</summary>
    public float[]? Color { get; set; }

    /// <summary>How far the UVs move each second, before tiling</summary>
    public float[] Scroll { get; set; } = [0, 0];
}

