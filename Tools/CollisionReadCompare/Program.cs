// Phase 6.2 check: Smithbox's old collision and navmesh geometry (a library and a helper per game) against
// Havok.Shared's CollisionGeometry over the unified library, per file.
//   CollisionReadCompare <GAME|ALL> [containers per category = 20] [files per container = 12] [report path]
// Run with the working directory at src/Smithbox.Data.

var gamePaths = File.ReadAllLines(Path.Combine("..", "..", "game_data.txt"))
    .Select(l => l.Split(':', 2)).Where(p => p.Length == 2)
    .ToDictionary(p => p[0].Trim(), p => p[1].Trim().Trim('"').Trim());

// --walls [maps = 10]: Sekiro wall shape keys, old (HKX2) against new, over the l (low) collision of a spread of maps
if (args.Length > 0 && args[0] == "--walls")
{
    string sdt = gamePaths["SDT"];
    var vfs = new CompundVirtualFileSystem([ArchiveBinderVirtualFileSystem.FromGameFolder(sdt, Game.SDT), new RealVirtualFileSystem(sdt, false)]);
    var bhds = vfs.GetFileNamesMatchingRecursive("/map", @"(?i)^l.*\.hkxbhd$").OrderBy(p => p).ToList();
    int keys = 0, different = 0, files = 0;
    foreach (var path in Spread(bhds, args.Length > 1 ? int.Parse(args[1]) : 10))
    {
        var bxf = BXF4.Read(vfs.ReadFileOrThrow(path), vfs.ReadFileOrThrow(Path.ChangeExtension(path, ".hkxbdt")));
        byte[] comp = bxf.Files.FirstOrDefault(f => f.Name.Contains(".compendium")) is { } cf ? Unpack(cf.Bytes.ToArray()) : null;
        var unified = comp == null ? null : HavokFile.ReadCompendium(comp, HavokProfile.SDT);
        foreach (var f in Spread(bxf.Files.Where(f => f.Name.Contains(".hkx.dcx")).ToList(), 8))
        {
            var (k, dk, first) = Probe.Walls(Unpack(f.Bytes.ToArray()), comp, unified);
            files++; keys += k; different += dk;
            if (first != null) Console.WriteLine($"{path} › {f.Name}: {dk} differ, e.g. {first}");
        }
    }
    Console.WriteLine($"walls: {files} files, {keys} shape keys, {different} differ");
    return 0;
}

// --packedrange <DS3 hkxbhd> <inner regex>: how far a compressed mesh's packed vertex indices reach
if (args.Length > 2 && args[0] == "--packedrange")
{
    string ds3 = gamePaths["DS3"];
    var vfs = new CompundVirtualFileSystem([ArchiveBinderVirtualFileSystem.FromGameFolder(ds3, Game.DS3), new RealVirtualFileSystem(ds3, false)]);
    var bxf = BXF4.Read(vfs.ReadFileOrThrow(args[1]), vfs.ReadFileOrThrow(Path.ChangeExtension(args[1], ".hkxbdt")));
    var inner = bxf.Files.First(f => Regex.IsMatch(f.Name, args[2]));
    Probe.PackedRange(DCX.Is(inner.Bytes) ? DCX.Decompress(inner.Bytes).ToArray() : inner.Bytes.ToArray());
    return 0;
}
string[] all = ["DES", "DS1", "DS1R", "DS2S", "BB", "DS3", "SDT", "ER", "NR", "AC6"];
var games = args.Length > 0 && args[0] != "ALL" ? [args[0]] : all;
int perCategory = args.Length > 1 ? int.Parse(args[1]) : 20;
int perContainer = args.Length > 2 ? int.Parse(args[2]) : 12;
string report = args.Length > 3 ? args[3] : Path.Combine("..", "..", "Documentation", "Claude", "Havok Library Survey", "Collision Read Compare.md");

var lines = new List<string>
{
    $"Generated by `Tools/CollisionReadCompare` on {DateTime.Now:yyyy-MM-dd HH:mm}: {perCategory} containers per category and {perContainer} files per container. " +
    "Smithbox's old collision and navmesh geometry (per-game library and helper) against Havok.Shared's `CollisionGeometry` over the unified library. " +
    "See [Phase 6.2](../Havok%20Phase%206.2%20Collision%20and%20Navmesh.md).",
    "",
    "Equal = same submeshes and triangles, every vertex bit for bit. Close = the same within 1e-4 (relative), from a different float formula. " +
    "Different = a submesh or triangle count differs, or a vertex is further off. New only / old only = the other path failed or drew nothing.",
    "",
    "| Game | Kind | Files | Both empty | Equal | Close | Different | New only | Old only | Both failed |",
    "|---|---|---|---|---|---|---|---|---|---|"
};
var details = new List<string>();

foreach (string gameName in games)
{
    if (!gamePaths.TryGetValue(gameName, out string root)) continue;
    var game = Enum.Parse<Game>(gameName);
    VirtualFileSystem fs;
    try { fs = new CompundVirtualFileSystem([ArchiveBinderVirtualFileSystem.FromGameFolder(root, game), new RealVirtualFileSystem(root, false)]); }
    catch { fs = new RealVirtualFileSystem(root, false); }
    var profile = HavokProfile.FromGame(gameName)!;

    var containers = fs.GetFileNamesMatchingRecursive("/", @"(?i)\.(hkxbhd|objbnd|geomhkxbnd|nvmhktbnd|hkx)(\.dcx)?$")
        .Select(p => p.Replace('\\', '/')).Distinct(StringComparer.OrdinalIgnoreCase).ToList();
    var picked = new List<(string Kind, string Path)>();
    foreach (var (kind, pattern) in new[]
             {
                 ("map collision", @"(?i)/map/.*\.hkxbhd$"),
                 ("map collision (loose)", @"(?i)/map/.*\.hkx(\.dcx)?$"),
                 ("object collision", @"(?i)\.(objbnd|geomhkxbnd)(\.dcx)?$"),
                 ("navmesh", @"(?i)\.nvmhktbnd(\.dcx)?$")
             })
        picked.AddRange(Spread(containers.Where(p => Regex.IsMatch(p, pattern)).OrderBy(p => p).ToList(), perCategory).Select(p => (kind, p)));

    var stats = new ConcurrentDictionary<(string Kind, string Outcome), int>();
    var diffs = new ConcurrentBag<(string Kind, string Text)>();
    void Count(string kind, string outcome) => stats.AddOrUpdate((kind, outcome), 1, (_, v) => v + 1);

    Parallel.ForEach(picked, new ParallelOptions { MaxDegreeOfParallelism = 8 }, c =>
    {
        List<(string Name, byte[] Bytes)> files;
        byte[] compendium = null;
        try
        {
            if (Regex.IsMatch(c.Path, @"(?i)\.hkx(\.dcx)?$")) files = [(Path.GetFileName(c.Path), Unpack(fs.ReadFileOrThrow(c.Path).ToArray()))];
            else
            {
                IBinder binder;
                if (c.Path.EndsWith("bhd", StringComparison.OrdinalIgnoreCase))
                {
                    var bhd = fs.ReadFileOrThrow(c.Path); var bdt = fs.ReadFileOrThrow(Path.ChangeExtension(c.Path, ".hkxbdt"));
                    binder = BXF4.IsBHD(bhd) ? BXF4.Read(bhd, bdt) : BXF3.Read(bhd, bdt);
                }
                else
                {
                    byte[] bnd = Unpack(fs.ReadFileOrThrow(c.Path).ToArray());
                    binder = BND4.Is(bnd) ? BND4.Read(bnd) : BND3.Read(bnd);
                }
                compendium = binder.Files.FirstOrDefault(f => f.Name.Contains(".compendium", StringComparison.OrdinalIgnoreCase)) is { } cf ? Unpack(cf.Bytes.ToArray()) : null;
                files = Spread(binder.Files.Where(f => Regex.IsMatch(f.Name, @"(?i)\.hkx(\.dcx)?$")).ToList(), perContainer)
                    .Select(f => (Path.GetFileName(f.Name.Replace('\\', '/')), Unpack(f.Bytes.ToArray()))).ToList();
            }
        }
        catch (Exception e) { diffs.Add((c.Kind, $"{c.Path}: unreadable container ({e.Message})")); return; }

        string kind = c.Kind.StartsWith("map collision") ? "map collision" : c.Kind;
        Lazy<HavokCompendium> unifiedCompendium = new(() => compendium == null ? null : HavokFile.ReadCompendium(compendium, profile));
        foreach (var (name, bytes) in files)
        {
            bool navmesh = kind == "navmesh";
            var (o, oe) = Try(() => navmesh ? Old.Navmesh(gameName, bytes) : Old.Collision(gameName, bytes, compendium));
            var (n, ne) = Try(() => navmesh ? New.Navmesh(profile, bytes) : New.Collision(profile, bytes, unifiedCompendium.Value));
            string where = $"{c.Path} › {name}";
            bool oEmpty = oe == null && o.Sum(s => s.Count) == 0, nEmpty = ne == null && n.Sum(s => s.Count) == 0;
            Count(kind, "files");
            if (oe != null && ne != null) { Count(kind, "both failed"); diffs.Add((kind, $"{where}: both failed (old {oe}; new {ne})")); continue; }
            if (oe == null && ne == null && oEmpty && nEmpty) { Count(kind, "both empty"); continue; }
            if (oe != null || oEmpty) { Count(kind, "new only"); diffs.Add((kind, $"{where}: new only (old {(oe ?? "drew nothing")})")); continue; }
            if (ne != null || nEmpty) { Count(kind, "old only"); diffs.Add((kind, $"{where}: old only (new {(ne ?? "drew nothing")})")); continue; }
            var (outcome, text) = Compare.Meshes(o, n);
            Count(kind, outcome);
            if (outcome == "different") diffs.Add((kind, $"{where}: {text}"));
        }
    });

    foreach (string kind in new[] { "map collision", "object collision", "navmesh" })
    {
        int S(string k) => stats.GetValueOrDefault((kind, k));
        if (S("files") == 0) continue;
        lines.Add($"| {gameName} | {kind} | {S("files")} | {S("both empty")} | {S("equal")} | {S("close")} | {S("different")} | {S("new only")} | {S("old only")} | {S("both failed")} |");
        Console.WriteLine(lines[^1]);
    }
    if (!diffs.IsEmpty)
    {
        details.Add($"### {gameName}");
        details.Add("");
        foreach (var g in diffs.GroupBy(d => (d.Kind, Reason(d.Text))).OrderByDescending(g => g.Count()))
            details.Add($"- {g.Key.Kind}, {g.Count()}×: {g.First().Text}");
        details.Add("");
    }
}

lines.Add("");
if (details.Count > 0) { lines.Add("## Differences"); lines.Add(""); lines.AddRange(details); }
File.WriteAllLines(report, lines);
foreach (var d in details) Console.WriteLine(d);
return 0;

static string Reason(string text) => Regex.Replace(text[(text.IndexOf(": ") + 2)..], @"\d+(\.\d+)?", "#");

static List<T> Spread<T>(List<T> items, int count) =>
    items.Count <= count ? items : Enumerable.Range(0, count).Select(i => items[(int)((long)i * items.Count / count)]).Distinct().ToList();

static byte[] Unpack(byte[] data) => DCX.Is(data) ? DCX.Decompress(data).ToArray() : data;

static (T, string) Try<T>(Func<T> f) where T : class
{
    try { return (f() ?? throw new InvalidDataException("nothing read"), null); }
    catch (Exception e) { return (null, e.GetType().Name + ": " + e.Message.Split('\n')[0]); }
}

/// <summary>Smithbox's reads before 6.2: the library and helper each game used.</summary>
public static class Old
{
    public static List<List<Vector3>> Collision(string game, byte[] data, byte[] compendium)
    {
        switch (game)
        {
            case "ER" or "NR" or "DB" or "DB_NT":
            {
                var s = new HKLib.Serialization.hk2018.Binary.HavokBinarySerializer();
                if (compendium != null) s.LoadCompendium(new MemoryStream(compendium));
                return OldHkLib2018.Collision((HKLib.hk2018.hkRootLevelContainer)s.Read(new MemoryStream(data)));
            }
            case "AC6":
            {
                var s = new HKLib.Serialization.hk2019.Binary.HavokBinarySerializer();
                if (compendium != null) s.LoadCompendium(new MemoryStream(compendium));
                return OldHkLib2019.Collision((HKLib.hk2019.hkRootLevelContainer)s.Read(new MemoryStream(data)));
            }
            case "SDT":
            {
                var c = compendium != null ? HKX2.TagFileDeserializer.ReadCompendium(compendium) : null;
                return OldHkx2.Collision((HKX2.hkRootLevelContainer)new HKX2.TagFileDeserializer().Deserialize(data, c));
            }
            case "DS3":
                return OldHkx2.Collision((HKX2.hkRootLevelContainer)new HKX2.PackFileDeserializer().Deserialize(new BinaryReaderEx(false, data)));
            case "BB":
                // the BB loop draws duplicates without their body; compare against what it meant to draw
                return OldSoulsFormats.Collision(HKX.Read(data, HKX.HKXVariation.HKXBloodBorne), fixedBB: true);
            default:
                return OldSoulsFormats.Collision(HKX.Read(data));
        }
    }

    public static List<List<Vector3>> Navmesh(string game, byte[] data)
    {
        (List<Vector3> Mesh, List<Vector3> Graph) r = game switch
        {
            "DS3" or "BB" => OldHkx2.Navmesh((HKX2.hkRootLevelContainer)new HKX2.PackFileDeserializer().Deserialize(new BinaryReaderEx(false, data))),
            "ER" or "NR" or "DB" or "DB_NT" => OldHkLib2018.Navmesh((HKLib.hk2018.hkRootLevelContainer)new HKLib.Serialization.hk2018.Binary.HavokBinarySerializer().Read(new MemoryStream(data))),
            "AC6" => OldHkLib2019.Navmesh((HKLib.hk2019.hkRootLevelContainer)new HKLib.Serialization.hk2019.Binary.HavokBinarySerializer().Read(new MemoryStream(data))),
            _ => throw new NotSupportedException($"Smithbox didn't draw {game} navmeshes")
        };
        return [r.Mesh ?? [], r.Graph ?? []];
    }
}

/// <summary>Smithbox's reads after 6.2: the steps HavokCollisionResource and HavokNavmeshResource take.</summary>
public static class New
{
    public static List<List<Vector3>> Collision(HavokProfile profile, byte[] data, HavokCompendium compendium) =>
        CollisionGeometry.Submeshes(HavokFile.Read(data, profile, compendium).Objects);

    public static List<List<Vector3>> Navmesh(HavokProfile profile, byte[] data)
    {
        var doc = HavokFile.Read(data, profile);
        var mesh = doc.ObjectsOf<IHavokNavMesh>().FirstOrDefault();
        var graph = doc.ObjectsOf<IHavokDirectedGraph>().FirstOrDefault();
        return [mesh == null ? [] : CollisionGeometry.NavMeshTriangles(mesh), graph == null ? [] : CollisionGeometry.GraphSegments(graph)];
    }
}

public static class Compare
{
    public static (string Outcome, string Text) Meshes(List<List<Vector3>> a, List<List<Vector3>> b)
    {
        a = Canonical(a); b = Canonical(b);
        if (a.Count != b.Count) return ("different", $"submeshes {a.Count} vs {b.Count} (vertices {a.Sum(s => s.Count)} vs {b.Sum(s => s.Count)})");
        bool close = false;
        for (int s = 0; s < a.Count; s++)
        {
            if (a[s].Count != b[s].Count) return ("different", $"submesh {s}: {a[s].Count / 3} vs {b[s].Count / 3} triangles");
            for (int i = 0; i < a[s].Count; i++)
            {
                if (a[s][i] == b[s][i]) continue;
                if (!Near(a[s][i], b[s][i])) return ("different", $"submesh {s} vertex {i}: {a[s][i]} vs {b[s][i]}");
                close = true;
            }
        }
        return (close ? "close" : "equal", null);
    }

    // submeshes in a fixed order: by size, then by their first vertex
    private static List<List<Vector3>> Canonical(List<List<Vector3>> meshes) =>
        meshes.Where(m => m.Count > 0).OrderBy(m => m.Count).ThenBy(m => Math.Round(m[0].X, 2)).ThenBy(m => Math.Round(m[0].Y, 2)).ThenBy(m => Math.Round(m[0].Z, 2)).ToList();

    private static bool Near(Vector3 x, Vector3 y) => Near(x.X, y.X) && Near(x.Y, y.Y) && Near(x.Z, y.Z);

    private static bool Near(float x, float y) => Math.Abs(x - y) <= 1e-4f * Math.Max(1f, Math.Abs(x));
}
