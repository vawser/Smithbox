using System.Collections;
using System.Collections.Concurrent;
using System.Reflection;
using System.Text.Json;
using System.Text.RegularExpressions;
using Andre.Core;
using Andre.IO.VFS;
using Havok;
using Havok.Files;
using SoulsFormats;

// Phase 6.3 check: the Havok Editor's read and save path before (HKLib 2018/2019 for the tagfile games, HKX2 for DS3)
// and after (HavokFile), per editor category, on game files. Also checks the two things the editor now does per SDK:
// hiding fields the game's registry doesn't give a class, and finding a class's meta (Assets/HAVOK/<sdk>).
//   HavokEditorRoundTrip <GAME|ALL> [containers per category = 12] [files per container = 8] [report path]
// Run with the working directory at src/Smithbox.Data.

var gamePaths = File.ReadAllLines(Path.Combine("..", "..", "game_data.txt"))
    .Select(l => l.Split(':', 2)).Where(p => p.Length == 2)
    .ToDictionary(p => p[0].Trim(), p => p[1].Trim().Trim('"').Trim());

string[] all = ["ER", "NR", "AC6", "DB_NT", "DS3", "SDT"];
var games = args.Length > 0 && args[0] != "ALL" ? [args[0]] : all;
int perCategory = args.Length > 1 ? int.Parse(args[1]) : 12;
int perContainer = args.Length > 2 ? int.Parse(args[2]) : 8;
string report = args.Length > 3 ? args[3] : Path.Combine("..", "..", "Documentation", "Claude", "Havok Library Survey", "Havok Editor Round Trip.md");

// The editor's categories, found as ProjectFileLocator finds them; the old path loaded the binder's compendium for
// animations and map collision only (AC6: always)
(string Category, string Pattern, bool OldCompendium)[] categories =
[
    ("Animation", @"(?i)\.anibnd(\.dcx)?$", true),
    ("Behavior", @"(?i)\.behbnd(\.dcx)?$", false),
    ("Character", @"(?i)\.chrbnd(\.dcx)?$", false),
    ("Map collision", @"(?i)/map/.*\.hkxbhd$", true),
    ("Asset collision", @"(?i)(/obj/.*\.objbnd|/asset/.*\.geomhkxbnd)(\.dcx)?$", false),
    ("Navmesh", @"(?i)\.nvmhktbnd(\.dcx)?$", false),
    ("Cutscene", @"(?i)\.(cutscenebnd|remobnd)(\.dcx)?$", false),
    ("Part", @"(?i)/parts/.*\.partsbnd(\.dcx)?$", false),
    ("Rumble", @"(?i)\.rumblebnd(\.dcx)?$", false),
];

var metaKeys = new Dictionary<string, HashSet<string>>();
foreach (var folder in new[] { "hk2014", "hk2018" })
{
    metaKeys[folder] = Directory.GetFiles(Path.Combine("Assets", "HAVOK", folder), "*.json")
        .Select(f => JsonDocument.Parse(File.ReadAllText(f)).RootElement.GetProperty("Type").GetString())
        .ToHashSet();
}
var metaHits = new ConcurrentDictionary<(string Folder, string Key), byte>();
var metaSeenFolders = new ConcurrentDictionary<string, byte>();

var lines = new List<string>
{
    $"Generated by `Tools/HavokEditorRoundTrip` on {DateTime.Now:yyyy-MM-dd HH:mm}: {perCategory} containers per category and {perContainer} files per container. " +
    "The Havok Editor's load and save before 6.3 (HKLib 2018/2019, HKX2) against `HavokFile.Read`/`Write`, with the compendium handling `HavokBank` uses. " +
    "See [Phase 6.3](../Havok%20Phase%206.3%20Havok%20Editor.md).",
    "",
    "- **Same data:** the new read equals the old one (types and fields by name). Counted where both read.",
    "- **Saved as stored:** a save without edits gives the stored bytes back, before (old writer) → after (`HavokFile.Write`).",
    "- **Round trip:** the saved bytes read back to an equal graph, and saving that again gives the same bytes.",
    "- **Hidden fields:** fields of the generated classes that the game's registry doesn't give the class, so the property view hides them. *Set* counts those holding a non-default value after a read, which would mean the field is in the file after all.",
    "",
    "| Game | Category | Files | Read: old → new | Same data | Saved as stored: old → new | Round trip | Hidden fields (set) |",
    "|---|---|---|---|---|---|---|---|"
};
var details = new List<string>();

foreach (string gameName in games)
{
    if (!gamePaths.TryGetValue(gameName, out string root)) continue;
    var game = Enum.Parse<Game>(gameName);
    VirtualFileSystem fs;
    try { fs = new CompundVirtualFileSystem([ArchiveBinderVirtualFileSystem.FromGameFolder(root, game), new RealVirtualFileSystem(root, false)]); }
    catch { fs = new RealVirtualFileSystem(root, false); }
    var profile = HavokProfile.FromGame(gameName)!;

    var containers = fs.GetFileNamesMatchingRecursive("/", @"(?i)\.(anibnd|behbnd|chrbnd|hkxbhd|objbnd|geomhkxbnd|nvmhktbnd|cutscenebnd|remobnd|partsbnd|rumblebnd)(\.dcx)?$")
        .Select(p => p.Replace('\\', '/')).Distinct(StringComparer.OrdinalIgnoreCase).OrderBy(p => p).ToList();

    var picked = new List<(string Category, bool OldCompendium, string Path)>();
    foreach (var (category, pattern, oldCompendium) in categories)
    {
        // The editor skips _sd (low detail) copies
        var matching = containers.Where(p => Regex.IsMatch(p, pattern) && !p.Contains("/sd/", StringComparison.OrdinalIgnoreCase)).ToList();
        picked.AddRange(Spread(matching, perCategory).Select(p => (category, oldCompendium, p)));
    }

    var stats = new ConcurrentDictionary<(string Category, string Key), int>();
    var diffs = new ConcurrentBag<(string Category, string Text)>();
    void Count(string category, string key, int n = 1) => stats.AddOrUpdate((category, key), n, (_, v) => v + n);

    Parallel.ForEach(picked, new ParallelOptions { MaxDegreeOfParallelism = 8 }, c =>
    {
        List<(string Name, byte[] Bytes)> files;
        byte[] compendiumBytes;
        try
        {
            IBinder binder;
            if (c.Path.EndsWith("bhd", StringComparison.OrdinalIgnoreCase))
            {
                var bhd = fs.ReadFileOrThrow(c.Path); var bdt = fs.ReadFileOrThrow(c.Path[..^3] + "bdt");
                binder = BXF4.IsBHD(bhd) ? BXF4.Read(bhd, bdt) : BXF3.Read(bhd, bdt);
            }
            else
            {
                byte[] bnd = Unpack(fs.ReadFileOrThrow(c.Path).ToArray());
                binder = BND4.Is(bnd) ? BND4.Read(bnd) : BND3.Read(bnd);
            }
            compendiumBytes = binder.Files.FirstOrDefault(f => f.Name.Contains(".compendium", StringComparison.OrdinalIgnoreCase)) is { } cf ? Unpack(cf.Bytes.ToArray()) : null;
            files = Spread(binder.Files.Where(f => !f.Name.Contains(".compendium", StringComparison.OrdinalIgnoreCase))
                    .Select(f => (Name: Path.GetFileName(f.Name.Replace('\\', '/')), Bytes: TryUnpack(f.Bytes.ToArray())))
                    .Where(f => f.Bytes != null && IsHavok(f.Bytes)).ToList(), perContainer);
        }
        catch (Exception e) { diffs.Add((c.Category, $"{c.Path}: unreadable container ({e.Message})")); return; }

        // As HavokBank: read once per binder, only for files that refer to it
        Lazy<HavokCompendium> compendium = new(() => compendiumBytes == null ? null : HavokFile.ReadCompendium(compendiumBytes, profile));

        foreach (var (name, bytes) in files)
        {
            string where = $"{c.Path} › {name}";
            Count(c.Category, "files");

            // Before 6.3
            var (oldRoot, oldError) = Try(() => Old.Read(gameName, bytes, c.OldCompendium || gameName == "AC6" ? compendiumBytes : null));
            if (oldError == null && Old.Supported(gameName))
            {
                Count(c.Category, "old read");
                var (oldBytes, _) = Try(() => Old.Write(gameName, oldRoot, compendiumBytes));
                if (oldBytes != null && oldBytes.AsSpan().SequenceEqual(bytes)) Count(c.Category, "old identical");
            }

            // After 6.3
            HavokDocument doc;
            try
            {
                var used = HavokFile.Sniff(bytes).UsesCompendium ? compendium.Value : null;
                doc = HavokFile.Read(bytes, profile, used);
            }
            catch (Exception e) { diffs.Add((c.Category, $"{where}: new read failed ({Short(e)})")); continue; }
            Count(c.Category, "new read");

            if (oldError == null && Old.Supported(gameName))
            {
                Count(c.Category, "compared");
                string difference = GraphCompare.CompareAcross(oldRoot, doc.Root);
                if (difference == null) Count(c.Category, "same data");
                else diffs.Add((c.Category, $"{where}: data differs from the old read at {difference}"));
            }

            try
            {
                byte[] written = HavokFile.Write(doc);
                if (written.AsSpan().SequenceEqual(bytes)) Count(c.Category, "new identical");

                var reread = HavokFile.Read(written, profile, HavokFile.Sniff(written).UsesCompendium ? compendium.Value : null);
                string graph = GraphCompare.Compare(doc.Root, reread.Root);
                byte[] again = HavokFile.Write(reread);
                if (graph == null && again.AsSpan().SequenceEqual(written)) Count(c.Category, "round trip");
                else diffs.Add((c.Category, graph != null ? $"{where}: re-read differs at {graph}" : $"{where}: second save differs"));
            }
            catch (Exception e) { diffs.Add((c.Category, $"{where}: save failed ({Short(e)})")); }

            // Field hiding and meta, over every Havok object the editor can show
            foreach (object obj in Walk(doc.Root))
            {
                Type type = obj.GetType();
                string folder = MetaFolder(type);
                if (folder != null)
                {
                    metaSeenFolders.TryAdd(folder, 0);
                    string key = Normalize(RelativeName(type));
                    foreach (string metaKey in metaKeys[folder])
                        if (Normalize(metaKey) == key) metaHits.TryAdd((folder, metaKey), 0);
                }

                foreach (FieldInfo field in Fields(type))
                {
                    if (HasField(profile, type, field.Name)) continue;
                    Count(c.Category, "hidden");
                    if (!IsDefault(field.GetValue(obj)))
                    {
                        Count(c.Category, "hidden set");
                        diffs.Add((c.Category, $"{where}: hidden field {type.Name}.{field.Name} holds {Describe(field.GetValue(obj))}"));
                    }
                }
            }
        }
    });

    foreach (var (category, _, _) in categories)
    {
        int S(string k) => stats.GetValueOrDefault((category, k));
        if (S("files") == 0) continue;
        string oldRead = Old.Supported(gameName) ? S("old read").ToString() : "—";
        string oldIdentical = Old.Supported(gameName) ? S("old identical").ToString() : "—";
        string same = Old.Supported(gameName) ? $"{S("same data")} / {S("compared")}" : "—";
        lines.Add($"| {gameName} | {category} | {S("files")} | {oldRead} → {S("new read")} | {same} | {oldIdentical} → {S("new identical")} | {S("round trip")} / {S("new read")} | {S("hidden")} ({S("hidden set")}) |");
        Console.WriteLine(lines[^1]);
    }

    if (!diffs.IsEmpty)
    {
        details.Add($"### {gameName}");
        details.Add("");
        foreach (var g in diffs.GroupBy(d => (d.Category, Reason(d.Text))).OrderByDescending(g => g.Count()))
            details.Add($"- {g.Key.Category}, {g.Count()}×: {g.First().Text}");
        details.Add("");
    }
}

lines.Add("");
lines.Add("## Meta lookup");
lines.Add("");
lines.Add("Meta files (`Assets/HAVOK/<folder>/*.json`) whose class turned up in the sampled files, found with the editor's lookup (namespace dropped, nesting separators ignored).");
lines.Add("");
lines.Add("| Folder | Meta files | Found | Not seen |");
lines.Add("|---|---|---|---|");
foreach (var (folder, keys) in metaKeys)
{
    if (!metaSeenFolders.ContainsKey(folder)) continue;
    var found = keys.Where(k => metaHits.ContainsKey((folder, k))).ToList();
    var missing = keys.Except(found).OrderBy(k => k).ToList();
    lines.Add($"| {folder} | {keys.Count} | {found.Count} | {(missing.Count == 0 ? "—" : string.Join(", ", missing.Select(m => $"`{m}`")))} |");
}
lines.Add("");

if (details.Count > 0) { lines.Add("## Differences"); lines.Add(""); lines.AddRange(details); }
File.WriteAllLines(report, lines);
foreach (var d in details.Take(80)) Console.WriteLine(d);
return 0;

static string Reason(string text) => Regex.Replace(text[(text.IndexOf(": ") + 2)..], @"\d+(\.\d+)?", "#");

static List<T> Spread<T>(List<T> items, int count) =>
    items.Count <= count ? items : Enumerable.Range(0, count).Select(i => items[(int)((long)i * items.Count / count)]).Distinct().ToList();

static byte[] Unpack(byte[] data) => DCX.Is(data) ? DCX.Decompress(data).ToArray() : data;

static byte[] TryUnpack(byte[] data)
{
    try { return Unpack(data); }
    catch { return null; }
}

static bool IsHavok(byte[] data)
{
    try { return HavokFile.Sniff(data).Container is HavokContainer.Packfile or HavokContainer.Tagfile; }
    catch { return false; }
}

static string Short(Exception e) => e.GetType().Name + ": " + e.Message.Split('\n')[0];

static (T, string) Try<T>(Func<T> f) where T : class
{
    try { return (f() ?? throw new InvalidDataException("nothing read"), null); }
    catch (Exception e) { return (null, Short(e)); }
}

// ---- The editor's per-SDK lookups, as Smithbox does them -------------------------------------------------------------

static IEnumerable<FieldInfo> Fields(Type type) => type.GetFields(BindingFlags.Instance | BindingFlags.Public);

static bool HasField(HavokProfile profile, Type type, string field) =>
    !type.Namespace!.StartsWith("Havok.hk", StringComparison.Ordinal) ||
    FieldPresence.Cache.GetOrAdd((profile.Game, type, field), k => HavokFile.HasField(profile, k.Type, k.Field));

static string MetaFolder(Type type) => type.Namespace?.Split('.') switch
{
    ["Havok", "hk2014", ..] => "hk2014",
    ["Havok", "hk2016" or "hk2018" or "hk2019", ..] => "hk2018",
    _ => null
};

static string RelativeName(Type type)
{
    string full = type.FullName ?? type.Name;
    if (full.Contains('`')) full = full.Split('`')[0];
    foreach (var prefix in new[] { "Havok.hk2014.", "Havok.hk2016.", "Havok.hk2018.", "Havok.hk2019." })
        if (full.StartsWith(prefix, StringComparison.Ordinal)) return full[prefix.Length..];
    return full;
}

static string Normalize(string name)
{
    foreach (var prefix in new[] { "HKLib.hk2018.", "HKLib.hk2019.", "HKX2." })
        if (name.StartsWith(prefix, StringComparison.Ordinal)) { name = name[prefix.Length..]; break; }
    return name.Replace("+", "").Replace(".", "");
}

static bool IsDefault(object value) => value switch
{
    null => true,
    string s => s.Length == 0,
    bool b => !b,
    System.Enum e => Convert.ToInt64(e) == 0,
    IConvertible c when value.GetType().IsPrimitive => c.ToDouble(null) == 0,
    ICollection list => list.Count == 0 || list.Cast<object>().All(IsDefault),
    _ when value.GetType().IsValueType => value.Equals(Activator.CreateInstance(value.GetType())),
    _ => false
};

static string Describe(object value) => value switch
{
    ICollection list => $"{list.Count} items",
    _ => value?.ToString() ?? "null"
};

/// <summary>Every Havok object reachable from the root: pointed-to objects, embedded records and list elements.</summary>
static IEnumerable<object> Walk(object root)
{
    var seen = new HashSet<object>(ReferenceEqualityComparer.Instance);
    var stack = new Stack<object>();
    stack.Push(root);
    while (stack.Count > 0)
    {
        object obj = stack.Pop();
        if (obj == null || obj is string || obj.GetType().IsPrimitive || obj is System.Enum) continue;
        if (obj is IEnumerable items and not string)
        {
            foreach (object item in items) stack.Push(item);
            continue;
        }
        if (obj.GetType().Namespace?.StartsWith("Havok.hk", StringComparison.Ordinal) != true) continue;
        if (!obj.GetType().IsValueType && !seen.Add(obj)) continue;
        yield return obj;
        foreach (FieldInfo field in Fields(obj.GetType())) stack.Push(field.GetValue(obj));
    }
}

static class FieldPresence
{
    public static readonly ConcurrentDictionary<(string Game, Type Type, string Field), bool> Cache = new();
}

/// <summary>The Havok Editor's read and save before 6.3: HavokTagSerializer (HKLib) and HKX2's packfile classes.</summary>
public static class Old
{
    public static bool Supported(string game) => game is "ER" or "NR" or "AC6" or "DB_NT" or "DB" or "DS3";

    public static object Read(string game, byte[] data, byte[] compendium)
    {
        switch (game)
        {
            case "ER" or "NR" or "DB" or "DB_NT":
            {
                var s = Serializer2018(game);
                if (compendium != null) s.LoadCompendium(new MemoryStream(compendium));
                return s.Read(new MemoryStream(data));
            }
            case "AC6":
            {
                var s = new HKLib.Serialization.hk2019.Binary.HavokBinarySerializer();
                if (compendium != null) s.LoadCompendium(new MemoryStream(compendium));
                return s.Read(new MemoryStream(data));
            }
            case "DS3":
                return new HKX2.PackFileDeserializer().Deserialize(new BinaryReaderEx(false, data));
            default:
                throw new NotSupportedException($"The Havok Editor didn't open {game} files");
        }
    }

    /// <summary>
    /// Save: 2018 never loaded the compendium (so files were written with their own types), AC6 always did
    /// </summary>
    public static byte[] Write(string game, object root, byte[] compendium)
    {
        switch (game)
        {
            case "ER" or "NR" or "DB" or "DB_NT":
            {
                using var stream = new MemoryStream();
                Serializer2018(game).Write((HKLib.hk2018.hkRootLevelContainer)root, stream);
                return stream.ToArray();
            }
            case "AC6":
            {
                var s = new HKLib.Serialization.hk2019.Binary.HavokBinarySerializer();
                if (compendium != null) s.LoadCompendium(new MemoryStream(compendium));
                using var stream = new MemoryStream();
                s.Write((HKLib.hk2019.hkRootLevelContainer)root, stream);
                return stream.ToArray();
            }
            case "DS3":
            {
                var bw = new BinaryWriterEx(false);
                new HKX2.PackFileSerializer().Serialize((HKX2.IHavokObject)root, bw);
                return bw.FinishBytes();
            }
            default:
                throw new NotSupportedException();
        }
    }

    private static HKLib.Serialization.hk2018.Binary.HavokBinarySerializer Serializer2018(string game) =>
        new(game == "NR" ? HKLib.Reflection.hk2018.HavokTypeRegistry.Nightreign : HKLib.Reflection.hk2018.HavokTypeRegistry.Instance);
}
