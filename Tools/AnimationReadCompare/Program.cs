// Phase 6.1 check: the renderer's old animation reader (SoulsFormats HKX for packfiles, the schema-less HavokTagfile for
// tagfiles) against the new one (HavokFile + the Havok.Shared views), over each game's character anibnds.
//   AnimationReadCompare <GAME|ALL> [binders per game = 40] [clips per binder = 40] [report path]
// Run with the working directory at src/Smithbox.Data. Every value is compared; floats bit for bit.

var gamePaths = File.ReadAllLines(Path.Combine("..", "..", "game_data.txt"))
    .Select(l => l.Split(':', 2)).Where(p => p.Length == 2)
    .ToDictionary(p => p[0].Trim(), p => p[1].Trim().Trim('"').Trim());
string[] animated = ["DS1", "DS1R", "BB", "DS3", "SDT", "ER", "NR", "AC6", "DES"];
var games = args.Length > 0 && args[0] != "ALL" ? [args[0]] : animated;
int perGame = args.Length > 1 ? int.Parse(args[1]) : 40;
int perBinder = args.Length > 2 ? int.Parse(args[2]) : 40;
string report = args.Length > 3 ? args[3] : Path.Combine("..", "..", "Documentation", "Claude", "Havok Library Survey", "Animation Read Compare.md");

var lines = new List<string>
{
    $"Generated by `Tools/AnimationReadCompare` on {DateTime.Now:yyyy-MM-dd HH:mm}, {perGame} anibnds per game and {perBinder} clips per anibnd. " +
    "The renderer's old animation reader (SoulsFormats HKX, the schema-less HavokTagfile) against the new one (Havok.Files and the Havok.Shared views). " +
    "See [Phase 6.1](../Havok%20Phase%206.1%20Renderer%20Animation.md).",
    "",
    "| Game | Skeletons: old / new / equal | Clips: old / new / equal | Clips the renderer can play (new) | New only (old failed) | Old only (new failed) | Different |",
    "|---|---|---|---|---|---|---|"
};
var details = new List<string>();

foreach (string gameName in games)
{
    if (!gamePaths.TryGetValue(gameName, out string? root)) continue;
    var game = Enum.Parse<Game>(gameName);
    VirtualFileSystem fs;
    try { fs = new CompundVirtualFileSystem([ArchiveBinderVirtualFileSystem.FromGameFolder(root, game), new RealVirtualFileSystem(root, false)]); }
    catch { fs = new RealVirtualFileSystem(root, false); }

    // /chr/cXXXX.anibnd, or deeper: DeS keeps chr/cXXXX/cXXXX.anibnd, and BB's dump has Loose/dvdroot_ps4/chr
    const string anibnd = @"(?i)^c\d{4}[^/]*\.anibnd(\.dcx)?$";
    var binders = fs.GetFileNamesMatchingRecursive("/chr", anibnd).ToList();
    if (binders.Count == 0) binders = fs.GetFileNamesMatchingRecursive("/", anibnd).Where(p => p.Replace('\\', '/').Contains("/chr/")).ToList();
    binders = binders.OrderBy(p => p).ToList();
    var sample = Spread(binders, perGame);
    var profile = HavokProfile.FromGame(gameName)!;
    var stats = new ConcurrentDictionary<string, int>();
    var diffs = new ConcurrentBag<string>();
    void Count(string key) => stats.AddOrUpdate(key, 1, (_, v) => v + 1);

    Parallel.ForEach(sample, new ParallelOptions { MaxDegreeOfParallelism = 8 }, path =>
    {
        IBinder binder;
        try
        {
            byte[] bytes = Unpack(fs.ReadFileOrThrow(path).ToArray());
            binder = BND4.Is(bytes) ? BND4.Read(bytes) : BND3.Read(bytes);
        }
        catch (Exception e) { diffs.Add($"{path}: binder unreadable ({e.Message})"); return; }

        byte[]? compendiumBytes = binder.Files.FirstOrDefault(f => f.ID == 7000000)?.Bytes.ToArray();
        HavokCompendium? compendium = null;
        try { if (compendiumBytes != null) compendium = HavokFile.ReadCompendium(Unpack(compendiumBytes), profile); }
        catch (Exception e) { diffs.Add($"{path}: new compendium unreadable ({e.Message})"); }

        int skeletonId = binder.Files.Any(f => f.ID == 4000000) ? 4000000 : 1000000;
        var skeletonFile = binder.Files.FirstOrDefault(f => f.ID == skeletonId);
        bool legacy = gameName is "DES" or "DS1" or "DS1R";
        var clips = Spread(binder.Files.Where(f => f.Name.Contains(".hkx", StringComparison.OrdinalIgnoreCase) &&
                                                   (legacy ? f.ID is >= 0 and <= 999999 : f.ID >= 1000000000)).ToList(), perBinder);

        int boneCount = 0;
        if (skeletonFile != null)
        {
            byte[] data = Unpack(skeletonFile.Bytes.ToArray());
            var (o, oe) = Try(() => Old.Skeleton(gameName, data, compendiumBytes));
            var (n, ne) = Try(() => New.Skeleton(profile, data, compendium));
            Tally("skeleton", o, oe, n, ne, $"{path} › {skeletonFile.Name}");
            boneCount = n?.Names.Length ?? o?.Names.Length ?? 0;
        }

        foreach (var clipFile in clips)
        {
            byte[] data = Unpack(clipFile.Bytes.ToArray());
            var (o, oe) = Try(() => Old.Clip(gameName, data, compendiumBytes));
            var (n, ne) = Try(() => New.Clip(profile, data, compendium));
            // a file with no clip the reader understands is null, not a failure
            Tally("clip", o, oe, n, ne, $"{path} › {clipFile.Name}");
        }

        void Tally<T>(string kind, T? o, string? oe, T? n, string? ne, string where) where T : class
        {
            if (oe == null) Count($"{kind} old");
            if (ne == null) Count($"{kind} new");
            if (ne == null && n != null) Count($"{kind} playable");
            if (oe == null && ne == null)
            {
                string? diff = Compare.Describe(o, n);
                if (diff == null) Count($"{kind} equal");
                else { Count("different"); diffs.Add($"{where}: {diff}"); }
            }
            else if (oe != null && ne == null) Count("new only");
            else if (oe == null && ne != null) { Count("old only"); diffs.Add($"{where}: new failed ({ne})"); }
        }
    });

    int S(string k) => stats.GetValueOrDefault(k);
    lines.Add($"| {gameName} | {S("skeleton old")} / {S("skeleton new")} / {S("skeleton equal")} | {S("clip old")} / {S("clip new")} / {S("clip equal")} | {S("clip playable")} | {S("new only")} | {S("old only")} | {S("different")} |");
    Console.WriteLine(lines[^1]);
    if (!diffs.IsEmpty)
    {
        details.Add($"### {gameName}");
        details.Add("");
        foreach (var g in diffs.GroupBy(d => d[(d.IndexOf(": ") + 2)..].Split(' ')[0]).OrderByDescending(g => g.Count()))
        {
            details.Add($"- {g.Count()}× like: {g.First()}");
        }
        details.Add("");
    }
}

lines.Add("");
lines.Add("Old = read without throwing by the old reader. Skeletons of DeS, and clips other than spline and interleaved, are beyond both. \"New only\" counts files the new reader reads and the old couldn't.");
lines.Add("");
if (details.Count > 0) { lines.Add("## Differences and failures"); lines.Add(""); lines.AddRange(details); }
File.WriteAllLines(report, lines);
foreach (var d in details) Console.WriteLine(d);
return 0;

static List<T> Spread<T>(List<T> items, int count) =>
    items.Count <= count ? items : Enumerable.Range(0, count).Select(i => items[(int)((long)i * items.Count / count)]).Distinct().ToList();

static byte[] Unpack(byte[] data) => DCX.Is(data) ? DCX.Decompress(data).ToArray() : data;

static (T?, string?) Try<T>(Func<T?> f) where T : class
{
    try { return (f(), null); }
    catch (Exception e) { return (null, e.GetType().Name + ": " + e.Message.Split('\n')[0]); }
}

/// <summary>What either reader hands the renderer: its HavokSkeletonData and clip constructor arguments.</summary>
public sealed record SkeletonValues(string[] Names, short[] Parents, HavokTransformData[] Pose);

public sealed record ClipValues(string Kind, int Tracks, int Blocks, int FramesPerBlock, int Frames, float Duration,
    float FrameDuration, byte[] Data, bool BigEndian, HavokTransformData[] Transforms, short[] TrackToBone, int BlendMode);

/// <summary>The renderer's reader before Phase 6.1 (Smithbox.Program/Renderer/Animation/HavokAnimationData.cs).</summary>
public static class Old
{
    public static SkeletonValues Skeleton(string game, byte[] data, byte[]? compendium)
    {
        if (HavokTagfile.IsTagfile(data))
        {
            HavokTagfile tag = HavokTagfile.Read(data, compendium != null ? HavokTagfile.ReadCompendium(Unpack(compendium)) : null);
            foreach (HavokTagfile.TagObject skeleton in tag.FindObjects("hkaSkeleton"))
            {
                var bones = skeleton.GetObjectArray("bones");
                return new SkeletonValues(bones.Select(b => b.GetString("name")).ToArray(), skeleton.GetInt16Array("parentIndices"),
                    skeleton.GetTransformArray("referencePose"));
            }
            throw new InvalidOperationException("Tagfile has no skeleton.");
        }

        HKX hkx = HKX.Read(data, Variation(game));
        foreach (HKX.HKXObject obj in hkx.DataSection.Objects)
        {
            if (obj is not HKX.HKASkeleton s) continue;
            int count = (int)s.Bones.Size;
            return new SkeletonValues(Enumerable.Range(0, count).Select(i => s.Bones[i].Name.GetString()).ToArray(),
                Enumerable.Range(0, count).Select(i => s.ParentIndices[i].data).ToArray(),
                Enumerable.Range(0, count).Select(i => ToTransform(s.Transforms[i])).ToArray());
        }
        throw new InvalidOperationException("Packfile has no skeleton.");
    }

    public static ClipValues? Clip(string game, byte[] data, byte[]? compendium)
    {
        if (HavokTagfile.IsTagfile(data))
        {
            HavokTagfile tag = HavokTagfile.Read(data, compendium != null ? HavokTagfile.ReadCompendium(Unpack(compendium)) : null);
            short[] trackToBone = [];
            int blend = 0;
            foreach (var binding in tag.FindObjects("hkaAnimationBinding"))
            {
                trackToBone = binding.GetInt16Array("transformTrackToBoneIndices");
                blend = BlendMode(binding.GetByte("blendHint"));
                break;
            }
            foreach (var a in tag.FindObjects("hkaSplineCompressedAnimation"))
                return new ClipValues("spline", a.GetInt32("numberOfTransformTracks"), a.GetInt32("numBlocks"), a.GetInt32("maxFramesPerBlock"),
                    a.GetInt32("numFrames"), a.GetSingle("duration"), a.GetSingle("frameDuration"), a.GetByteArray("data"), false, [], trackToBone, blend);
            foreach (var a in tag.FindObjects("hkaInterleavedUncompressedAnimation"))
                return new ClipValues("interleaved", a.GetInt32("numberOfTransformTracks"), 0, 0, 0, a.GetSingle("duration"), 0, [], false,
                    a.GetTransformArray("transforms"), trackToBone, blend);
            return null;
        }

        HKX hkx = HKX.Read(data, Variation(game));
        HKX.HKASplineCompressedAnimation? spline = null;
        HKX.HKAInterleavedUncompressedAnimation? interleaved = null;
        HKX.HKAAnimationBinding? b = null;
        foreach (var obj in hkx.DataSection.Objects)
        {
            switch (obj)
            {
                case HKX.HKASplineCompressedAnimation s: spline = s; break;
                case HKX.HKAInterleavedUncompressedAnimation i: interleaved = i; break;
                case HKX.HKAAnimationBinding x: b = x; break;
            }
        }
        short[] map = b == null ? [] : Enumerable.Range(0, (int)b.TransformTrackToBoneIndices.Size).Select(i => b.TransformTrackToBoneIndices[i].data).ToArray();
        int blendMode = BlendMode((byte)(b?.BlendHint ?? HKX.AnimationBlendHint.NORMAL));
        if (spline != null)
            return new ClipValues("spline", spline.TransformTrackCount, spline.BlockCount, spline.FramesPerBlock, spline.FrameCount,
                spline.Duration, spline.FrameDuration, spline.GetData(), hkx.Header.Endian == 0, [], map, blendMode);
        if (interleaved != null)
            return new ClipValues("interleaved", interleaved.TransformTrackCount, 0, 0, 0, interleaved.Duration, 0, [], false,
                Enumerable.Range(0, (int)interleaved.Transforms.Size).Select(i => ToTransform(interleaved.Transforms[i])).ToArray(), map, blendMode);
        return null;
    }

    private static int BlendMode(byte hint) => hint is 1 or 2 ? hint : 0;

    private static HavokTransformData ToTransform(HKX.Transform t) => new()
    {
        Translation = new(t.Position.Vector.X, t.Position.Vector.Y, t.Position.Vector.Z),
        Rotation = new(t.Rotation.Vector.X, t.Rotation.Vector.Y, t.Rotation.Vector.Z, t.Rotation.Vector.W),
        Scale = new(t.Scale.Vector.X, t.Scale.Vector.Y, t.Scale.Vector.Z)
    };

    private static HKX.HKXVariation Variation(string game) => game switch
    {
        "DES" => HKX.HKXVariation.HKXDeS,
        "DS1" or "DS1R" => HKX.HKXVariation.HKXDS1,
        "BB" => HKX.HKXVariation.HKXBloodBorne,
        _ => HKX.HKXVariation.HKXDS3
    };

    private static byte[] Unpack(byte[] data) => DCX.Is(data) ? DCX.Decompress(data).ToArray() : data;
}

/// <summary>The renderer's reader after Phase 6.1: the same steps as HavokAnimationReader.</summary>
public static class New
{
    public static SkeletonValues Skeleton(HavokProfile profile, byte[] data, HavokCompendium? compendium)
    {
        var doc = HavokFile.Read(data, profile, compendium);
        var s = doc.ObjectsOf<IHavokSkeleton>().FirstOrDefault() ?? throw new InvalidOperationException("The file has no skeleton.");
        return new SkeletonValues(Enumerable.Range(0, s.BoneCount).Select(i => s.GetBoneName(i) ?? "").ToArray(),
            Enumerable.Range(0, s.BoneCount).Select(s.GetParent).ToArray(),
            Enumerable.Range(0, s.BoneCount).Select(i => ToTransform(s.GetReferencePose(i))).ToArray());
    }

    public static ClipValues? Clip(HavokProfile profile, byte[] data, HavokCompendium? compendium)
    {
        var doc = HavokFile.Read(data, profile, compendium);
        var b = doc.ObjectsOf<IHavokAnimationBinding>().FirstOrDefault();
        short[] map = b?.TransformTrackToBoneIndices.ToArray() ?? [];
        int blend = b?.BlendHint is 1 or 2 ? b.BlendHint : 0;
        if (doc.ObjectsOf<IHavokSplineAnimation>().FirstOrDefault() is { } s)
            return new ClipValues("spline", s.TransformTrackCount, s.BlockCount, s.MaxFramesPerBlock, s.FrameCount, s.Duration, s.FrameDuration,
                s.Data.ToArray(), doc.Source.BigEndian, [], map, blend);
        if (doc.ObjectsOf<IHavokInterleavedAnimation>().FirstOrDefault() is { } i)
            return new ClipValues("interleaved", i.TransformTrackCount, 0, 0, 0, i.Duration, 0, [], false,
                Enumerable.Range(0, i.TransformCount).Select(k => ToTransform(i.GetTransform(k))).ToArray(), map, blend);
        return null;
    }

    private static HavokTransformData ToTransform(HavokQsTransform t) => new() { Translation = t.Translation, Rotation = t.Rotation, Scale = t.Scale };
}

public static class Compare
{
    /// <summary>The first difference between two readers' values, or null when they're equal.</summary>
    public static string? Describe(object? a, object? b)
    {
        if (a == null || b == null) return a == b ? null : $"one reader has no clip (old {(a == null ? "null" : "value")}, new {(b == null ? "null" : "value")})";
        switch (a, b)
        {
            case (SkeletonValues x, SkeletonValues y):
                if (x.Names.Length != y.Names.Length) return $"bones {x.Names.Length} vs {y.Names.Length}";
                for (int i = 0; i < x.Names.Length; i++)
                {
                    if (x.Names[i] != y.Names[i]) return $"bone {i} name \"{x.Names[i]}\" vs \"{y.Names[i]}\"";
                    if (i >= x.Parents.Length || x.Parents[i] != y.Parents[i]) return $"bone {i} parent";
                    if (!Same(x.Pose[i], y.Pose[i])) return $"bone {i} reference pose {Show(x.Pose[i])} vs {Show(y.Pose[i])}";
                }
                return null;
            case (ClipValues x, ClipValues y):
                if (x.Kind != y.Kind) return $"kind {x.Kind} vs {y.Kind}";
                if ((x.Tracks, x.Blocks, x.FramesPerBlock, x.Frames) != (y.Tracks, y.Blocks, y.FramesPerBlock, y.Frames))
                    return $"counts {(x.Tracks, x.Blocks, x.FramesPerBlock, x.Frames)} vs {(y.Tracks, y.Blocks, y.FramesPerBlock, y.Frames)}";
                if (Bits(x.Duration) != Bits(y.Duration) || Bits(x.FrameDuration) != Bits(y.FrameDuration)) return "durations";
                if (x.BigEndian != y.BigEndian) return "byte order";
                if (!x.Data.AsSpan().SequenceEqual(y.Data)) return $"spline data ({x.Data.Length} vs {y.Data.Length} bytes)";
                if (x.Transforms.Length != y.Transforms.Length) return $"transforms {x.Transforms.Length} vs {y.Transforms.Length}";
                for (int i = 0; i < x.Transforms.Length; i++) if (!Same(x.Transforms[i], y.Transforms[i])) return $"transform {i}";
                if (!x.TrackToBone.AsSpan().SequenceEqual(y.TrackToBone)) return "track to bone map";
                if (x.BlendMode != y.BlendMode) return $"blend {x.BlendMode} vs {y.BlendMode}";
                return null;
        }
        return "different value types";
    }

    private static int Bits(float f) => BitConverter.SingleToInt32Bits(f);

    private static bool Same(HavokTransformData a, HavokTransformData b) =>
        Bits(a.Translation.X) == Bits(b.Translation.X) && Bits(a.Translation.Y) == Bits(b.Translation.Y) && Bits(a.Translation.Z) == Bits(b.Translation.Z) &&
        Bits(a.Rotation.X) == Bits(b.Rotation.X) && Bits(a.Rotation.Y) == Bits(b.Rotation.Y) && Bits(a.Rotation.Z) == Bits(b.Rotation.Z) && Bits(a.Rotation.W) == Bits(b.Rotation.W) &&
        Bits(a.Scale.X) == Bits(b.Scale.X) && Bits(a.Scale.Y) == Bits(b.Scale.Y) && Bits(a.Scale.Z) == Bits(b.Scale.Z);

    private static string Show(HavokTransformData t) => $"T{t.Translation} R{t.Rotation} S{t.Scale}";
}
