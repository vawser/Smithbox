using System.Xml.Linq;
using Havok;
using Havok.Reflection;

/// <summary>
/// --layoutcheck: checks Havok.Core's layout engine, which derives console layouts (BB) from PC registries.
/// 1. Recomputing each registry with MSVC rules must give back the registry's own layouts.
/// 2. Recomputing ER's registry with Itanium rules must give DB_NT's layouts, which the DB_NT overlay proves from files.
/// </summary>
public static class LayoutCheck
{
    public static List<string> Run()
    {
        var lines = new List<string>
        {
            "# Havok layout engine check",
            "",
            $"Generated by `Tools/HavokLibSurvey --layoutcheck` on {DateTime.Now:yyyy-MM-dd HH:mm}. Checks `Havok.Reflection.HavokLayout`, which recomputes a registry's record layouts under other C++ ABI rules.",
            "",
            "## 1. MSVC recompute gives back each registry",
            ""
        };

        foreach (var profile in new[] { HavokProfile.DS3, HavokProfile.DS1R, HavokProfile.SDT, HavokProfile.ER, HavokProfile.NR, HavokProfile.AC6, HavokProfile.DB_NT })
        {
            var registry = profile.GetRegistry()!;
            var layout = new HavokLayout(8, HavokLayoutRules.Msvc, profile.Sdk == HavokSdk.Hk2014);
            var diffs = Compare(registry, registry, layout);
            int records = registry.Types.Count(t => t.Kind == HavokType.TypeKind.Record);
            lines.Add($"- **{profile.Game}** ({registry.SdkVersion}{(registry.Overlays.Count > 0 ? " + " + string.Join(", ", registry.Overlays) : "")}): " +
                      $"{records - diffs.Count}/{records} records identical, {layout.Notes.Count} notes");
            foreach (var d in diffs.Take(15)) lines.Add($"  - {d}");
            foreach (var n in layout.Notes.Take(profile == HavokProfile.DS3 ? 100 : 10)) lines.Add($"  - note: {n}");
        }

        lines.Add("");
        lines.Add("## 2. ER registry + Itanium rules vs the DB_NT registry");
        lines.Add("");
        var er = HavokProfile.ER.GetRegistry()!;
        var dbnt = HavokProfile.DB_NT.GetRegistry()!;
        var itanium = new HavokLayout(8, HavokLayoutRules.Itanium);

        // the types the DB_NT overlay changed: proven from DB_NT files
        var overlay = XElement.Load(Path.Join(HavokProfile.ResourceFolder, "HavokTypeRegistry20180100_DB_NT.xml"));
        var changedNames = overlay.Elements("HavokType").Where(e => e.Attribute("New") == null)
            .Select(e => e.Attribute("Name")!.Value).ToHashSet();

        var all = Compare(er, dbnt, itanium, t => changedNames.Contains(t.Name) ? t : null);
        var changedTypes = dbnt.Types.Where(t => t.Kind == HavokType.TypeKind.Record && changedNames.Contains(t.Name)).ToList();
        var rest = Compare(er, dbnt, itanium, t => changedNames.Contains(t.Name) ? null : t);
        lines.Add($"- **Types the overlay changes** (proven from DB_NT files): {changedTypes.Count - all.Count}/{changedTypes.Count} match the Itanium recompute.");
        foreach (var d in all.Take(40)) lines.Add($"  - {d}");
        lines.Add($"- **Types the overlay keeps** from ER: {rest.Count} predicted to move under Itanium. These are only wrong if DB_NT files use them (the {dbnt.Count} registry types include many no DB_NT file has).");
        foreach (var d in rest.Take(25)) lines.Add($"  - {d}");
        lines.Add($"- {itanium.Notes.Count} notes");
        foreach (var n in itanium.Notes.Take(20)) lines.Add($"  - note: {n}");
        return lines;
    }

    /// <summary>
    /// Each record of <paramref name="expected" /> whose layout differs from the one computed from the same type in
    /// <paramref name="source" />. <paramref name="filter" /> picks the expected types to compare (null skips).
    /// </summary>
    public static List<string> Compare(HavokTypeRegistry source, HavokTypeRegistry expected, HavokLayout layout,
        Func<HavokType, HavokType> filter = null)
    {
        var diffs = new List<string>();
        foreach (var e in expected.Types.Where(t => t.Kind == HavokType.TypeKind.Record).OrderBy(t => t.Identity, StringComparer.Ordinal))
        {
            if (filter != null && filter(e) == null) continue;
            var s = source.GetType(e.Identity);
            if (s == null) continue;
            HavokTypeLayout l;
            try { l = layout.Get(s); }
            catch (Exception ex) { diffs.Add($"`{e.Identity}`: {ex.Message}"); continue; }

            var own = e.Fields.Skip(e.Parent?.Fields.Count ?? 0).ToList();
            var srcOwn = s.Fields.Skip(s.Parent?.Fields.Count ?? 0).ToList();
            var problems = new List<string>();
            if (l.Size != e.Size) problems.Add($"size {l.Size} vs {e.Size}");
            if (srcOwn.Count != own.Count) problems.Add($"member count {srcOwn.Count} vs {own.Count}");
            else
                for (int i = 0; i < own.Count; i++)
                    if (l.MemberOffsets[i] != own[i].Offset)
                        problems.Add($"{own[i].Name}@{l.MemberOffsets[i]} vs {own[i].Offset}");
            if (problems.Count > 0) diffs.Add($"`{e.Identity}`: {string.Join(", ", problems.Take(4))}");
        }
        return diffs;
    }
}

/// <summary>
/// --buildlayoutoverlay GAME: an overlay for a console game whose files carry no type sections (BB), derived from its
/// PC registry by recomputing every layout under the game's ABI rules. Only types whose size or member offsets change
/// are written; each is the base element with those values replaced, so names, hashes and enums stay the base's.
/// </summary>
public static class LayoutOverlay
{
    public static List<string> Write(HavokProfile profile, HavokLayoutRules rules, string pcGame)
    {
        var lines = new List<string>();
        string basePath = Path.Join(HavokProfile.ResourceFolder, profile.RegistryFile!);
        var registry = HavokTypeRegistry.Load(basePath);
        var baseXml = XElement.Load(basePath);
        var elements = baseXml.Elements().SelectMany(x => x.Elements()).ToDictionary(e => int.Parse(e.Attribute("Id")!.Value));

        var identities = new Dictionary<int, string>();
        string Identity(int id)
        {
            if (identities.TryGetValue(id, out var cached)) return cached;
            var e = elements[id];
            var name = e.Attribute("Name")!.Value;
            var ps = e.Element("Template")?.Elements().ToList();
            var identity = ps == null || ps.Count == 0
                ? name
                : name + "<" + string.Join(", ", ps.Select(p => p.Attribute("Kind")!.Value == "Type"
                    ? Identity(int.Parse(p.Attribute("Value")!.Value))
                    : p.Attribute("Value")!.Value)) + ">";
            identities[id] = identity;
            return identity;
        }

        var layout = new HavokLayout(profile.PointerSize, rules, profile.Sdk == HavokSdk.Hk2014);
        var root = new XElement("HavokTypeRegistryOverlay",
            new XAttribute("Base", baseXml.Attribute("Version")?.Value ?? ""),
            new XAttribute("Game", profile.Game),
            new XComment($" {profile.Game} changes to {Path.GetFileName(basePath)}: the {pcGame} layouts recomputed with {rules.Name} C++ ABI rules " +
                         $"by the buildlayoutoverlay mode of Tools/HavokLibSurvey ({profile.Game}'s files carry no type sections). " +
                         "The same rules on ER's registry predict every DB_NT layout (Havok Library Survey/Layout Check.md). "));
        int records = 0, arrays = 0;
        foreach (var (id, e) in elements.OrderBy(x => x.Key))
        {
            var t = registry.GetType(Identity(id));
            if (t == null || t.Kind is not (HavokType.TypeKind.Record or HavokType.TypeKind.Array)) continue;
            var l = layout.Get(t);
            var members = e.Element("Members")?.Elements("Member").ToList() ?? new List<XElement>();
            bool sizeChanged = l.Size != t.Size;
            bool offsetsChanged = members.Count == l.MemberOffsets.Count &&
                                  members.Where((m, i) => int.Parse(m.Attribute("Offset")!.Value) != l.MemberOffsets[i]).Any();
            if (t.Kind == HavokType.TypeKind.Record && members.Count != l.MemberOffsets.Count)
                throw new InvalidDataException($"{t.Identity}: {members.Count} members in the XML, {l.MemberOffsets.Count} in the registry.");
            if (!sizeChanged && !offsetsChanged) continue;

            var changed = new XElement(e);
            changed.SetAttributeValue("Size", l.Size);
            var changedMembers = changed.Element("Members")?.Elements("Member").ToList() ?? new List<XElement>();
            for (int i = 0; i < changedMembers.Count && i < l.MemberOffsets.Count; i++)
                changedMembers[i].SetAttributeValue("Offset", l.MemberOffsets[i]);
            root.Add(changed);
            if (t.Kind == HavokType.TypeKind.Record) records++; else arrays++;
        }

        string path = Path.Combine("..", "Havok", "Havok.Core", "Res", $"{Path.GetFileNameWithoutExtension(profile.RegistryFile)}_{profile.Game}.xml");
        root.Save(path);
        lines.Add($"- Wrote `{Path.GetFileName(path)}`: {records} records and {arrays} fixed arrays change layout under {rules.Name} rules ({layout.Notes.Count} notes).");
        return lines;
    }
}
