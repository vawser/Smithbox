using System.Text;

public static class Report
{
    public static void Write(string reportPath, string goldenPath, string game, string root, string fsNote, string[] args, List<string> coreRegistry,
        Dictionary<string, int> categoryCounts, int containersSampled, List<FileResult> results,
        List<(string Path, string Error)> containerErrors, TimeSpan elapsed, List<string> typeDiff = null)
    {
        var sb = new StringBuilder();
        var files = results.Where(r => r.Sniff.Container != "Compendium").ToList();

        sb.AppendLine($"# Havok Library Survey: {game}");
        sb.AppendLine();
        sb.AppendLine($"Generated by `Tools/HavokLibSurvey` on {DateTime.Now:yyyy-MM-dd HH:mm}, args `{string.Join(' ', args)}`, {elapsed.TotalSeconds:F0}s.");
        sb.AppendLine($"Game folder `{root}` ({fsNote}). {containersSampled} containers sampled, {files.Count} Havok files, {results.Count - files.Count} compendiums.");
        sb.AppendLine();
        sb.AppendLine("Columns: **Read** = read without throwing. **Write** = wrote without throwing. **Bytes** = written file identical to the original. " +
                      "**Graph** = re-read graph equal to the first read, field by field (n/a for SoulsFormats). **Fixed** = writing the re-read graph gives the same bytes as the first write.");
        sb.AppendLine();

        // Havok.Core (Phase 1)
        sb.AppendLine("## Havok.Core checks");
        sb.AppendLine();
        var sniffDiffs = results.Where(r => r.CoreSniffDiff != null).ToList();
        sb.AppendLine(sniffDiffs.Count == 0
            ? $"- **Header sniffing:** `HavokFileInfo.Read` agrees with the survey sniffer on all {results.Count} files."
            : $"- **Header sniffing:** {sniffDiffs.Count}/{results.Count} files disagree.");
        foreach (var g in sniffDiffs.GroupBy(r => r.CoreSniffDiff).OrderByDescending(g => g.Count()).Take(10))
            sb.AppendLine($"  - {g.Count()}× `{g.Key}`, e.g. `{g.First().Container}` › `{g.First().Inner}`");
        if (coreRegistry != null)
            foreach (var l in coreRegistry) sb.AppendLine(l.Replace("- **", "- **Registry ").Replace("**:", ":**").Replace("** (", ":** ("));
        sb.AppendLine();

        if (typeDiff != null)
        {
            sb.AppendLine("## Types described by the files vs the registry (--typediff)");
            sb.AppendLine();
            foreach (var l in typeDiff) sb.AppendLine(l);
            sb.AppendLine();
        }

        // Containers
        sb.AppendLine("## Containers");
        sb.AppendLine();
        sb.AppendLine("| Category | In game | Files surveyed |");
        sb.AppendLine("|---|---|---|");
        foreach (var (cat, count) in categoryCounts.OrderBy(k => k.Key))
            sb.AppendLine($"| {cat} | {count} | {files.Count(f => f.Category == cat)} |");
        sb.AppendLine();

        // Formats
        sb.AppendLine("## Formats seen");
        sb.AppendLine();
        sb.AppendLine("| Format | Files | Categories |");
        sb.AppendLine("|---|---|---|");
        foreach (var g in results.GroupBy(f => f.Sniff.FormatKey).OrderByDescending(g => g.Count()))
            sb.AppendLine($"| {g.Key} | {g.Count()} | {string.Join(", ", g.Select(f => f.Category).Distinct().OrderBy(c => c))} |");
        sb.AppendLine();

        // Tagfile layouts: the section names and padding that make up each SDK's dialect
        var layouts = files.Where(f => f.Layout != null).GroupBy(f => (f.Sniff.FormatKey, f.Layout)).OrderBy(g => g.Key.FormatKey).ToList();
        if (layouts.Count > 0)
        {
            sb.AppendLine("## Tagfile layouts");
            sb.AppendLine();
            foreach (var g in layouts.Take(20))
                sb.AppendLine($"- {g.Key.FormatKey} ({g.Count()} files): `{g.Key.Layout}`");
            sb.AppendLine();
        }

        // Library matrix
        sb.AppendLine("## Library results by format");
        sb.AppendLine();
        sb.AppendLine("| Library | Format | Tried | Read | Write | Bytes | Graph | Fixed | Read ms (avg) | Write ms (avg) |");
        sb.AppendLine("|---|---|---|---|---|---|---|---|---|---|");
        var runs = files.SelectMany(f => f.Libs.Select(l => (File: f, Lib: l))).ToList();
        foreach (var g in runs.GroupBy(x => (x.Lib.Lib, x.File.Sniff.FormatKey)).OrderBy(g => g.Key.FormatKey).ThenBy(g => g.Key.Lib))
        {
            var l = g.Select(x => x.Lib).ToList();
            var writable = l.Any(x => x.WriteSupported);
            string Frac(Func<LibResult, bool> pred, IEnumerable<LibResult> of) { var o = of.ToList(); return $"{o.Count(pred)}/{o.Count}"; }
            var read = l.Where(x => x.Read).ToList();
            var written = l.Where(x => x.Write).ToList();
            var reread = l.Where(x => x.Reread).ToList();
            sb.AppendLine($"| {g.Key.Lib} | {g.Key.FormatKey} | {l.Count} | {Frac(x => x.Read, l)} | " +
                          $"{(writable ? Frac(x => x.Write, read) : "—")} | {(writable ? Frac(x => x.ByteIdentical, written) : "—")} | " +
                          $"{(writable && l.Any(x => x.GraphCompared) ? Frac(x => x.GraphDiff == null, reread) : "n/a")} | " +
                          $"{(writable ? Frac(x => x.FixedPoint, reread) : "—")} | " +
                          $"{(read.Count > 0 ? read.Average(x => x.ReadMs) : 0):F1} | {(written.Count > 0 ? written.Average(x => x.WriteMs) : 0):F1} |");
        }
        sb.AppendLine();

        // Unified engine parity
        var unifiedRuns = runs.Where(x => x.Lib.Lib.StartsWith("Unified") || x.Lib.Lib.StartsWith("Generated")).ToList();
        if (unifiedRuns.Count > 0)
        {
            sb.AppendLine("## Unified tagfile engine vs HKLib");
            sb.AppendLine();
            sb.AppendLine("**Same read** = the unified engine's object graph equals HKLib's, field by field. " +
                          "**Same write** = the unified engine writes the same bytes as HKLib. **Bytes** = the unified write equals the original file.");
            sb.AppendLine();
            sb.AppendLine("| Engine | Format | Tried | Read (HKLib) | Same read | Same write | Bytes |");
            sb.AppendLine("|---|---|---|---|---|---|---|");
            foreach (var g in unifiedRuns.GroupBy(x => (x.Lib.Lib, x.File.Sniff.FormatKey)).OrderBy(g => g.Key.FormatKey).ThenBy(g => g.Key.Lib))
            {
                var l = g.Select(x => x.Lib).ToList();
                var hk = g.Select(x => x.File.Libs.FirstOrDefault(h => h.Lib == x.Lib.ParityWith)).Where(h => h != null).ToList();
                var compared = l.Where(x => x.ParityCompared).ToList();
                var bothWrote = l.Where(x => x.ParityBytesEqual != null).ToList();
                var written = l.Where(x => x.Write).ToList();
                sb.AppendLine($"| {g.Key.Lib} | {g.Key.FormatKey} | {l.Count} | {l.Count(x => x.Read)} ({hk.Count(x => x.Read)}) | " +
                              $"{compared.Count(x => x.ParityGraphDiff == null)}/{compared.Count} | " +
                              $"{bothWrote.Count(x => x.ParityBytesEqual == true)}/{bothWrote.Count} | {written.Count(x => x.ByteIdentical)}/{written.Count} |");
            }
            sb.AppendLine();

            foreach (var g in unifiedRuns.Where(x => x.Lib.ParityGraphDiff != null).GroupBy(x => x.Lib.Lib))
            {
                sb.AppendLine($"- **{g.Key}** read differs from HKLib ({g.Count()}×), e.g.:");
                foreach (var x in g.Take(5)) sb.AppendLine($"  - `{x.File.Inner}`: `{x.Lib.ParityGraphDiff}`");
            }
            var meshRuns = runs.Where(x => x.Lib.Lib == "Generated 2014 packfile" && (x.Lib.MeshTriangles > 0 || x.Lib.MeshDecodeDiff != null)).ToList();
            if (meshRuns.Count > 0)
            {
                sb.AppendLine($"- **Compressed mesh decoding** (hk2014 port vs HKX2): {meshRuns.Count(x => x.Lib.MeshDecodeDiff == null)}/{meshRuns.Count} files decode the same, " +
                              $"{meshRuns.Sum(x => x.Lib.MeshTriangles)} triangles compared.");
                foreach (var x in meshRuns.Where(x => x.Lib.MeshDecodeDiff != null).Take(5))
                    sb.AppendLine($"  - `{x.File.Inner}`: {x.Lib.MeshDecodeDiff}");
            }

            foreach (var g in runs.Where(x => x.Lib.SectionDiff != null && !x.Lib.Lib.EndsWith("legacy")).GroupBy(x => x.Lib.Lib))
            {
                sb.AppendLine($"- **{g.Key}** writes that aren't byte-identical ({g.Count()}×), by section (original→written):");
                foreach (var s in g.GroupBy(x => x.File.Category).SelectMany(c => c.Take(3)).Take(12))
                    sb.AppendLine($"  - {s.File.Category} `{s.File.Inner}`: {s.Lib.SectionDiff}");
            }
            foreach (var g in unifiedRuns.Where(x => x.Lib.ParityBytesEqual == false).GroupBy(x => x.Lib.Lib))
            {
                sb.AppendLine($"- **{g.Key}** write differs from HKLib's ({g.Count()}×), e.g.:");
                foreach (var x in g.Take(3)) sb.AppendLine($"  - `{x.File.Inner}` ({x.File.Sniff.FormatKey})");
            }
            sb.AppendLine();
        }

        // By category
        sb.AppendLine("## Read success by category");
        sb.AppendLine();
        var libs = runs.Select(x => x.Lib.Lib).Distinct().OrderBy(n => n).ToList();
        sb.AppendLine($"| Category | Files | {string.Join(" | ", libs)} |");
        sb.AppendLine($"|---|---|{string.Concat(libs.Select(_ => "---|"))}");
        foreach (var g in files.GroupBy(f => f.Category).OrderBy(g => g.Key))
        {
            var cells = libs.Select(lib =>
            {
                var l = g.SelectMany(f => f.Libs).Where(x => x.Lib == lib).ToList();
                return l.Count == 0 ? "—" : $"{l.Count(x => x.Read)}/{l.Count}";
            });
            sb.AppendLine($"| {g.Key} | {g.Count()} | {string.Join(" | ", cells)} |");
        }
        sb.AppendLine();

        sb.AppendLine("## Byte-identical writes by category");
        sb.AppendLine();
        sb.AppendLine("Written files identical to the original, of those written.");
        sb.AppendLine();
        sb.AppendLine($"| Category | {string.Join(" | ", libs)} |");
        sb.AppendLine($"|---|{string.Concat(libs.Select(_ => "---|"))}");
        foreach (var g in files.GroupBy(f => f.Category).OrderBy(g => g.Key))
        {
            var cells = libs.Select(lib =>
            {
                var l = g.SelectMany(f => f.Libs).Where(x => x.Lib == lib && x.Write).ToList();
                return l.Count == 0 ? "—" : $"{l.Count(x => x.ByteIdentical)}/{l.Count}";
            });
            sb.AppendLine($"| {g.Key} | {string.Join(" | ", cells)} |");
        }
        sb.AppendLine();

        // the few that aren't, by name, where a category is nearly all identical
        foreach (var lib in libs)
            foreach (var g in files.GroupBy(f => f.Category).OrderBy(g => g.Key))
            {
                var misses = g.Where(f => f.Libs.Any(x => x.Lib == lib && x.Write && !x.ByteIdentical)).ToList();
                if (misses.Count is > 0 and <= 5)
                    sb.AppendLine($"- {lib}, {g.Key}: not identical: {string.Join(", ", misses.Select(f => $"`{f.Container}` › `{f.Inner}`"))}");
            }
        sb.AppendLine();

        // Errors
        sb.AppendLine("## Failures (grouped by message)");
        sb.AppendLine();
        foreach (var lib in libs)
        {
            var errs = runs.Where(x => x.Lib.Lib == lib)
                .Select(x => (x.File, Stage: x.Lib.ReadError != null ? "read" : x.Lib.WriteError != null ? "write" : x.Lib.RereadError != null ? "reread" : null,
                              Msg: x.Lib.ReadError ?? x.Lib.WriteError ?? x.Lib.RereadError))
                .Where(x => x.Msg != null)
                .GroupBy(x => (x.Stage, x.Msg))
                .OrderByDescending(g => g.Count())
                .ToList();
            if (errs.Count == 0) continue;
            sb.AppendLine($"### {lib}");
            sb.AppendLine();
            foreach (var g in errs.Take(12))
            {
                var ex = g.First().File;
                sb.AppendLine($"- **{g.Count()}× {g.Key.Stage}** `{g.Key.Msg}` — e.g. `{ex.Container}` › `{ex.Inner}` ({ex.Sniff.FormatKey})");
            }
            sb.AppendLine();
        }

        var diffs = runs.Where(x => x.Lib.GraphDiff != null).GroupBy(x => x.Lib.Lib).ToList();
        if (diffs.Count > 0)
        {
            sb.AppendLine("## Graph differences after a round trip (first 8 per library)");
            sb.AppendLine();
            foreach (var g in diffs)
            {
                sb.AppendLine($"### {g.Key}");
                sb.AppendLine();
                foreach (var x in g.Take(8))
                    sb.AppendLine($"- `{x.File.Inner}`: `{x.Lib.GraphDiff}`");
                sb.AppendLine();
            }
        }

        var byteDiffs = runs.Where(x => x.Lib.Write && !x.Lib.ByteIdentical).GroupBy(x => x.Lib.Lib).ToList();
        if (byteDiffs.Count > 0)
        {
            sb.AppendLine("## Byte differences after a write (first 8 per library)");
            sb.AppendLine();
            foreach (var g in byteDiffs)
            {
                sb.AppendLine($"### {g.Key}");
                sb.AppendLine();
                foreach (var x in g.Take(8))
                    sb.AppendLine($"- `{x.File.Inner}` ({x.File.Sniff.FormatKey}): first diff at 0x{x.Lib.FirstByteDiff:X}, size {x.Lib.SizeDelta:+#;-#;0}");
                sb.AppendLine();
            }
        }

        if (containerErrors.Count > 0)
        {
            sb.AppendLine("## Containers that couldn't be opened");
            sb.AppendLine();
            foreach (var g in containerErrors.GroupBy(e => e.Error).OrderByDescending(g => g.Count()))
                sb.AppendLine($"- **{g.Count()}×** `{g.Key}` — e.g. `{g.First().Path}`");
            sb.AppendLine();
        }

        // Classes
        sb.AppendLine("## Classes by format (files containing each)");
        sb.AppendLine();
        foreach (var g in files.GroupBy(f => f.Sniff.FormatKey).OrderBy(g => g.Key))
        {
            var counts = g.SelectMany(f => f.Classes).GroupBy(c => c).OrderByDescending(c => c.Count()).ThenBy(c => c.Key).ToList();
            sb.AppendLine($"### {g.Key} ({counts.Count} classes)");
            sb.AppendLine();
            sb.AppendLine(string.Join(", ", counts.Take(150).Select(c => $"`{c.Key}` {c.Count()}")) + (counts.Count > 150 ? ", …" : ""));
            sb.AppendLine();
        }

        File.WriteAllText(reportPath, sb.ToString());

        // Golden set: one file per (category, format, class set)
        var golden = new StringBuilder();
        golden.AppendLine("# category\tformat\tcontainer\tinner file\tclasses");
        foreach (var g in results.GroupBy(f => (f.Category, f.Sniff.FormatKey, string.Join(",", f.Classes))).OrderBy(g => g.Key.Category).ThenBy(g => g.Key.FormatKey))
        {
            var f = g.First();
            golden.AppendLine($"{f.Category}\t{f.Sniff.FormatKey}\t{f.Container}\t{f.Inner}\t{string.Join(",", f.Classes)}");
        }
        File.WriteAllText(goldenPath, golden.ToString());
    }
}
